const { newSession, humanClick, humanType } = require('./record');
const fs = require('fs');
(async () => {
  const setupUrl = fs.readFileSync('/root/.vegaduta/auth/first-run-setup.txt', 'utf8').match(/http:\/\/localhost:3000\/login\?setup=[\w-]+/)[0];
  const pw = fs.readFileSync('/home/user/stack/owner-password.txt', 'utf8').trim();
  const { browser, context, page, rec } = await newSession({ outDir: '/home/user/rec/out/01-setup' });
  await page.goto(setupUrl, { waitUntil: 'load' });
  await page.waitForTimeout(1500);
  await rec.start(page);
  await page.waitForTimeout(1200);
  rec.mark('choose');
  await humanClick(page, page.getByText('Use a password', { exact: false }), { delay: 700, settle: 900 });
  await page.screenshot({ path: '/home/user/rec/shots/setup-step2.png' });
  const pwInputs = page.locator('input[type="password"]');
  const n = await pwInputs.count();
  console.log('password inputs:', n);
  rec.mark('type-password');
  await humanType(page, pwInputs.nth(0), pw, { cps: 18 });
  if (n > 1) await humanType(page, pwInputs.nth(1), pw, { cps: 22 });
  await page.screenshot({ path: '/home/user/rec/shots/setup-step3.png' });
  const submit = page.locator('button[type="submit"], button:has-text("Continue"), button:has-text("Set"), button:has-text("Save"), button:has-text("Create"), button:has-text("Unlock"), button:has-text("Finish")').first();
  rec.mark('submit');
  await humanClick(page, submit, { delay: 600, settle: 500 });
  await page.waitForURL(u => !u.toString().includes('setup='), { timeout: 30000 }).catch(e => console.log('no redirect yet', e.message));
  await page.waitForTimeout(4500);
  rec.mark('landed');
  await page.screenshot({ path: '/home/user/rec/shots/after-setup.png' });
  console.log('url now', page.url());
  const frames = await rec.stop();
  await context.storageState({ path: '/home/user/stack/owner-state.json' });
  console.log('frames', frames);
  await browser.close();
})().catch(async e => { console.error('FAILED', e); process.exit(1); });
