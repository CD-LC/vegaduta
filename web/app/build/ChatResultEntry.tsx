// @ts-nocheck
"use client";

// Split out of ChatPane.tsx (behaviour unchanged): one "result" entry of the
// build chat thread - outcome line, engine chip, changed files (click to
// copy), skipped files, diff, branch / PR links and "Undo this change".
import { useMemo } from "react";
import {
  Check,
  CheckCircle2,
  Copy,
  ExternalLink,
  GitBranch,
  GitPullRequest,
  Loader2,
  Undo2,
  XCircle,
} from "lucide-react";
import { Button } from "../components/ui/button";
import { useTranslations } from "../lib/i18n";
import PoweredByChip from "../components/PoweredByChip";
import { parseDiff, diffFileStats } from "./suggestions";
import { BUILD_STRINGS as S } from "./buildStrings";

/** Unified diff, collapsed by default, with +/- colouring that does not rely
 * on colour alone (the +/- characters stay visible). */
function DiffView({ diff }: { diff: string }) {
  const { lines, truncated } = useMemo(() => parseDiff(diff), [diff]);
  const adds = lines.filter((l) => l.kind === "add").length;
  const dels = lines.filter((l) => l.kind === "del").length;
  const tone: Record<string, string> = {
    add: "bg-[color-mix(in_srgb,var(--state-success)_10%,transparent)] text-[var(--state-success)]",
    del: "bg-[color-mix(in_srgb,var(--state-error)_10%,transparent)] text-[var(--state-error)]",
    hunk: "text-sky-700 dark:text-sky-300",
    meta: "text-muted-foreground",
    ctx: "text-foreground/80",
  };
  return (
    <details className="mt-2 rounded-md border border-border bg-background/60">
      <summary className="cursor-pointer select-none px-2 py-1 text-xs font-medium text-muted-foreground hover:text-foreground">
        View changes{" "}
        <span className="font-normal">
          (<span className="text-[var(--state-success)]">+{adds}</span>{" "}
          <span className="text-[var(--state-error)]">&minus;{dels}</span>)
        </span>
      </summary>
      <pre
        tabIndex={0}
        aria-label={S.diffLabel}
        className="max-h-64 overflow-auto border-t border-border py-1 font-mono text-[11px] leading-snug"
      >
        {lines.map((l, i) => (
          <div key={i} className={`w-max min-w-full whitespace-pre px-2 ${tone[l.kind]}`}>
            {l.text || " "}
          </div>
        ))}
        {truncated && <div className="px-2 text-muted-foreground">… diff truncated</div>}
      </pre>
    </details>
  );
}

export function ChatResultEntry({
  entry,
  index,
  undoable,
  fileSet,
  copiedPath,
  onCopyFile,
  busy,
  disabled,
  undoing,
  onUndo,
}) {
  const t = useTranslations("appBuilder");
  // Per-file +/- counts from the turn's diff — the "where is the change"
  // answer on every file chip, without opening the folded diff.
  const fileStats = useMemo(() => {
    const m = new Map<string, { adds: number; dels: number }>();
    for (const s of diffFileStats(entry.diff || "")) m.set(s.path, s);
    return m;
  }, [entry.diff]);
  return (
    <div
      className={`rounded-lg border px-3 py-2 text-sm text-foreground ${
        entry.success ? "" : "border-destructive/40 bg-destructive/5"
      }`}
      style={
        entry.success
          ? {
              borderColor: "color-mix(in srgb, var(--state-success) 40%, transparent)",
              background: "color-mix(in srgb, var(--state-success) 5%, transparent)",
            }
          : undefined
      }
    >
      <div className="flex flex-wrap items-center gap-1.5 font-medium">
        {entry.success ? (
          <CheckCircle2 aria-hidden="true" size={14} style={{ color: "var(--state-success)" }} />
        ) : (
          <XCircle aria-hidden="true" size={14} className="text-destructive" />
        )}
        {entry.success
          ? t("appliedResultText", { count: entry.filesChanged?.length || 0 })
          : t("failedResultText", { error: entry.error || "" })}
        {entry.via === "on-device" && (
          <PoweredByChip
            source="device"
            model={entry.poweredBy?.model}
            prefix="Generated"
            title="Generated by a model running on your device — free, and your code never left this browser until it was committed to your repo"
            className="ms-1 font-normal"
          />
        )}
        {entry.via === "hosted" && entry.poweredBy && (
          <PoweredByChip
            source={entry.poweredBy.source}
            provider={entry.poweredBy.provider}
            model={entry.poweredBy.model}
            prefix="Generated by"
            className="ms-1 font-normal"
          />
        )}
      </div>
      {entry.success && entry.summary && <p className="mt-1.5 text-sm text-foreground/90">{entry.summary}</p>}
      {entry.success && entry.filesChanged?.length > 0 && (
        <div className="mt-1.5 flex flex-wrap gap-1">
          {entry.filesChanged.map((path) => {
            const available = (fileSet || []).some((f) => f.path === path);
            const stat = fileStats.get(path);
            return (
              <button
                key={path}
                type="button"
                disabled={!available}
                onClick={() => onCopyFile(path)}
                aria-label={S.copyFileLabel(path)}
                title={available ? S.copyFileLabel(path) : path}
                className="inline-flex items-center gap-1 rounded border border-border bg-muted/40 px-1.5 py-0.5 font-mono text-[11px] text-muted-foreground hover:bg-accent/60 hover:text-foreground disabled:cursor-default disabled:opacity-70 disabled:hover:bg-muted/40"
              >
                {path}
                {stat && (stat.adds > 0 || stat.dels > 0) && (
                  <span className="tabular-nums">
                    <span className="text-[var(--state-success)]">+{stat.adds}</span>{" "}
                    <span className="text-[var(--state-error)]">−{stat.dels}</span>
                  </span>
                )}
                {available &&
                  (copiedPath === path ? (
                    <Check size={11} aria-hidden="true" />
                  ) : (
                    <Copy size={11} aria-hidden="true" />
                  ))}
              </button>
            );
          })}
        </div>
      )}
      {entry.skippedFiles?.length > 0 && (
        <div className="mt-1 text-xs text-[var(--state-warning)]">
          Not changed (too large to edit safely in one go - ask for a smaller change): {entry.skippedFiles.join(", ")}
        </div>
      )}
      {entry.success && entry.diff && <DiffView diff={entry.diff} />}
      {entry.success && (entry.branch || entry.prUrl) && (
        <div className="mt-2 flex flex-wrap items-center gap-2">
          {entry.branch && (
            <span className="state-pill" style={{ ["--state" as string]: "var(--state-queued)" }}>
              <GitBranch aria-hidden="true" size={11} /> {entry.branch}
            </span>
          )}
          {entry.prUrl ? (
            <a
              href={entry.prUrl}
              target="_blank"
              rel="noopener noreferrer"
              className="inline-flex items-center gap-1 text-xs font-medium text-primary hover:underline"
            >
              <GitPullRequest aria-hidden="true" size={12} />
              {entry.prNumber ? `PR #${entry.prNumber}` : "View PR"} <ExternalLink aria-hidden="true" size={10} />
            </a>
          ) : entry.branch ? (
            <span className="text-xs text-muted-foreground">Branch pushed</span>
          ) : null}
        </div>
      )}
      {entry.success && entry.undone && (
        <p className="mt-2 flex items-center gap-1.5 text-xs text-muted-foreground">
          <Undo2 size={12} aria-hidden="true" /> Reverted to the version before this change.
        </p>
      )}
      {entry.success && entry.undo && !entry.undone && (
        <div className="mt-2">
          <Button
            variant="outline"
            size="sm"
            className="h-8 gap-1.5 text-xs"
            disabled={!undoable || busy || disabled || undoing != null}
            title={
              undoable
                ? "Restore the files this change modified to how they were before it"
                : "A later change touched the same files, so this can no longer be undone safely"
            }
            onClick={onUndo}
          >
            {undoing === index ? (
              <Loader2 aria-hidden="true" size={12} className="animate-spin" />
            ) : (
              <Undo2 aria-hidden="true" size={12} />
            )}{" "}
            Undo this change
          </Button>
          {entry.undo.created?.length > 0 && (
            <span className="ms-2 text-[11px] text-muted-foreground">
              New file{entry.undo.created.length > 1 ? "s" : ""} ({entry.undo.created.join(", ")}) would stay.
            </span>
          )}
        </div>
      )}
    </div>
  );
}
