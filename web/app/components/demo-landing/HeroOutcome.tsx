import Link from "next/link";
import { useRouter } from "next/navigation";
import {
  ArrowRight,
  Play,
  Pause,
  Check,
  Sparkles,
  Mail,
  ShieldCheck,
  Clock,
  X,
  Headset,
  Siren,
  GitPullRequest,
  Activity,
  Phone,
  TrendingUp,
} from "lucide-react";
import { useTranslations } from "../../lib/i18n";
import { FREE_MODE } from "../../lib/freeMode";
import { PLATFORM_FACTS } from "../../lib/platform-facts";
import { useJourney } from "../../lib/journey";
import { sendLandingEvent } from "./landingBeacon";
import PowerDial from "./PowerDial";
import { queueMagicPrompt } from "../try/magicPrefill";
import BrandText from "../BrandText";
import BuildConsole from "./HeroBuildConsole";

// Workload chips (2026-09-22 pivot — see header). These are JOBS a technical
// visitor would hand the platform, not business personas: ids key the
// h2_w_* i18n strings and BUILD_LOGS (./HeroBuildConsole), and the chip's "run this spec"
// link hands the brief to the on-page live studio via queueMagicPrompt —
// they deliberately do NOT carry /try persona ids, because no DemoPersona
// wire value describes a technical workload.
const WORKLOADS: Array<{ id: string; icon: typeof Headset }> = [
  { id: "support", icon: Headset },
  { id: "oncall", icon: Siren },
  { id: "code", icon: GitPullRequest },
  { id: "digest", icon: Activity },
  { id: "voice", icon: Phone },
  // 2026-09-28: the sales-automation bundle (CRM_LEAD + BULK_EMAIL nodes,
  // reply/bounce detection, schedules) is live in prod; it earns a chip.
  { id: "sales", icon: TrendingUp },
];

// Capability marquee - every chip is a shipped, code-backed capability (see
// the honesty ledger above). Rendered twice for the seamless loop; the second
// copy is aria-hidden. .mkt-marquee pauses on hover/focus and collapses to a
// scrollable row under reduced motion (marketing-system.css section 7).
// 2026-09-28: h2_fact3 ("46 built-in tools") and h2_fact4 ("20 curated MCP
// servers") had drifted from lib/platform-facts.ts (40+ / uncounted) and are
// retired from the strip; the tool count now renders from PLATFORM_FACTS, and
// four capabilities shipped since 2026-09-17 take the freed slots (h3_m_*).
// 2026-10-03: h1/lead moved to h4_* (the page now leads with trust — Lab,
// evals, approvals — not only with building) and four h4_m_* items joined
// the marquee. New keys rather than edited ones, so locales with an older
// translation fall back to the new English instead of showing a stale claim.
const MARQUEE_KEYS = [
  "h2_fact5",
  "h2_fact1",
  "h3_m_apps",
  "h4_m_lab",
  "h2_m6",
  "h2_fact2",
  "h2_m7",
  "h3_m_crm",
  "h4_m_skills",
  "h2_m8",
  "h3_tools",
  "h2_m9",
  "h3_m_versions",
  "h4_m_teams",
  "h2_m10",
  "h3_m_poweredBy",
  "h2_m11",
  "h4_m_memory",
  "h3_m_sso",
  "h2_m12",
] as const;

// Workload auto-rotation: stops for good on the first click or hover, and
// never runs under reduced motion. 6.5s gives one full console pass (type
// the spec, stream six build lines, land on the ship line) plus a beat of
// dwell before the next workload loads.
const ROTATE_MS = 6500;

const VIDEO_WEBM = "/media/landing/demo-60s.webm";
const VIDEO_MP4 = "/media/landing/demo-60s.mp4";
const VIDEO_POSTER = "/media/landing/demo-poster.jpg";

const EMAIL_RE = /^[^\s@]+@[^\s@]+\.[^\s@]+$/;

function withEmail(href: string, email: string): string {
  const joiner = href.includes("?") ? "&" : "?";
  return `${href}${joiner}email=${encodeURIComponent(email.trim())}`;
}

export default function HeroOutcome() {
  const t = useTranslations("landing");
  const router = useRouter();
  const journey = useJourney();
  const tried = journey.stage === "keep";

  const [persona, setPersona] = useState<string>(WORKLOADS[0].id);
  const [autoRotate, setAutoRotate] = useState(true);
  const [marqueePaused, setMarqueePaused] = useState(false);
  const [email, setEmail] = useState("");
  const [emailError, setEmailError] = useState(false);

  // The 60s walkthrough now lives ONLY in the dialog (the build console took
  // the inline frame) — opened on demand, so no autoplay plumbing is needed.
  const dialogRef = useRef<HTMLDialogElement | null>(null);
  const dialogVideoRef = useRef<HTMLVideoElement | null>(null);
  const [reduced, setReduced] = useState(false);

  // Reduced motion gates the console's typing animation AND the workload
  // auto-rotation — detected once, before either can start.
  useEffect(() => {
    const mq = window.matchMedia("(prefers-reduced-motion: reduce)");
    setReduced(mq.matches);
  }, []);

  // Workload auto-rotation: stops for good on the first click or hover, and
  // never starts under reduced motion.
  useEffect(() => {
    if (!autoRotate || reduced) return undefined;
    const id = window.setInterval(() => {
      setPersona((cur) => {
        const i = WORKLOADS.findIndex((p) => p.id === cur);
        return WORKLOADS[(i + 1) % WORKLOADS.length].id;
      });
    }, ROTATE_MS);
    return () => window.clearInterval(id);
  }, [autoRotate, reduced]);

  const openDialog = useCallback(() => {
    sendLandingEvent("hero_watch_click");
    const d = dialogRef.current;
    if (!d) return;
    if (typeof d.showModal === "function") d.showModal();
    else d.setAttribute("open", "");
    const dv = dialogVideoRef.current;
    if (dv) {
      dv.currentTime = 0;
      dv.muted = false;
      dv.play().catch(() => {});
    }
  }, []);

  const closeDialog = useCallback(() => {
    const d = dialogRef.current;
    dialogVideoRef.current?.pause();
    if (d?.open) d.close();
  }, []);

  // The console's "run this spec" line: hand the exact sentence the visitor
  // watched compile to the live studio on this page (see magicPrefill.ts),
  // then let the #live-studio anchor scroll them to it.
  const runSpec = useCallback(() => {
    sendLandingEvent("hero_try_click");
    queueMagicPrompt(t(`h2_w_${persona}_brief`));
  }, [t, persona]);

  function onEmailStart(e: FormEvent<HTMLFormElement>) {
    e.preventDefault();
    if (!EMAIL_RE.test(email.trim())) {
      setEmailError(true);
      return;
    }
    setEmailError(false);
    sendLandingEvent("hero_email_start");
    router.push(withEmail(journey.signupHref, email));
  }

  return (
    <div data-testid="hero-outcome">
      <div className="grid items-center gap-10 lg:grid-cols-[1.02fr_0.98fr] lg:gap-14">
        {/* ---------------- Text column ---------------- */}
        <div className="text-start">
          {/* Tagline pill — the platform's promise, not a pricing claim, so it
              reads true in both builds (2026-10-09; replaced the "free for 3
              months" eyebrow). Free mode adds the four ways to power it. */}
          <div className="mb-5 space-y-3">
            <div className="flex flex-wrap items-center gap-x-3 gap-y-2">
              <span className="mkt-pill mkt-pill--accent">
                <Sparkles className="size-3.5" aria-hidden="true" />
                {t("h5_tagline")}
              </span>
            </div>
            {FREE_MODE && <PowerDial />}
          </div>

          <h1 className="mkt-h1 text-balance">
            {t("h5_h1")} <span className="mkt-gradient-text">{t("h5_h1Em")}</span>
          </h1>

          <p className="mkt-lead mkt-ink-2 mt-5 max-w-xl text-pretty">
            <BrandText text={t("h5_lead")} />
          </p>

          {/* Workload row — each chip swaps the spec the console compiles */}
          <div className="mt-6">
            <p className="mkt-ui-label mkt-ink-3 mb-2">{t("h2_forLabel")}</p>
            <div className="flex flex-wrap gap-2" onMouseEnter={() => setAutoRotate(false)}>
              {WORKLOADS.map(({ id, icon: Icon }) => {
                const on = id === persona;
                return (
                  <button
                    key={id}
                    type="button"
                    aria-pressed={on}
                    onClick={() => {
                      setPersona(id);
                      setAutoRotate(false);
                      sendLandingEvent("hero_persona_click");
                    }}
                    className="mkt-pill inline-flex items-center gap-1.5 border-0 bg-transparent p-0 px-3 py-1.5 shadow-none transition-colors"
                    style={
                      on
                        ? {
                            background: "var(--mkt-accent)",
                            color: "var(--accent-fg, #fff)",
                            border: "1px solid var(--mkt-accent)",
                          }
                        : {
                            background: "var(--mkt-surface)",
                            color: "var(--mkt-ink-2)",
                            border: "1px solid var(--mkt-line)",
                          }
                    }
                  >
                    <Icon className="size-3.5" aria-hidden="true" />
                    {t(`h2_w_${id}_label`)}
                  </button>
                );
              })}
            </div>
          </div>

          {/* The ask */}
          <div className="mt-6">
            {tried ? (
              <div className="flex flex-wrap items-center gap-3">
                <Link
                  href={journey.signupHref}
                  onClick={() => sendLandingEvent("hero_keep_agent_click")}
                  className="mkt-btn mkt-btn-primary mkt-btn-lg"
                >
                  {t("hero_ctaKeepAgent")} <ArrowRight className="size-4" aria-hidden="true" />
                </Link>
                <Link
                  href={journey.tryHref}
                  onClick={() => sendLandingEvent("hero_try_click")}
                  className="mkt-btn mkt-btn-secondary mkt-btn-lg"
                >
                  {t("hero_ctaReopenSandbox")}
                </Link>
              </div>
            ) : (
              <form onSubmit={onEmailStart} className="flex flex-col gap-2 sm:flex-row sm:items-start" noValidate>
                <label className="sr-only" htmlFor="hero-email">
                  {t("h2_emailLabel")}
                </label>
                <div className="flex-1">
                  <div className="relative">
                    <Mail
                      className="pointer-events-none absolute start-3 top-1/2 size-4 -translate-y-1/2"
                      style={{ color: "var(--mkt-ink-3)" }}
                      aria-hidden="true"
                    />
                    <input
                      id="hero-email"
                      type="email"
                      inputMode="email"
                      autoComplete="email"
                      value={email}
                      onChange={(e) => {
                        setEmail(e.target.value);
                        if (emailError) setEmailError(false);
                      }}
                      placeholder={t("h2_emailPlaceholder")}
                      aria-invalid={emailError || undefined}
                      aria-describedby={emailError ? "hero-email-error" : undefined}
                      className="mkt-input w-full"
                      // .mkt-input is unlayered and wins over Tailwind's pl-9,
                      // so the icon inset has to be inline.
                      style={{ height: "3rem", paddingInlineStart: "2.5rem" }}
                    />
                  </div>
                  {emailError && (
                    <p id="hero-email-error" className="mkt-field__error mt-1">
                      {t("h2_emailInvalid")}
                    </p>
                  )}
                </div>
                <button
                  type="submit"
                  className="mkt-btn mkt-btn-primary mkt-btn-lg w-full border-0 sm:w-auto"
                  data-testid="hero-email-start"
                >
                  {t("h2_ctaStart")} <ArrowRight className="size-4" aria-hidden="true" />
                </button>
              </form>
            )}
            <p className="mkt-caption mkt-ink-2 mt-3 flex flex-wrap items-center gap-x-3 gap-y-1">
              <span className="inline-flex items-center gap-1.5">
                <Clock className="size-3.5" aria-hidden="true" />
                {t(FREE_MODE ? "h5_ctaNoteFreeMode" : "hero_ctaNote")}
              </span>
              {!tried && (
                <Link
                  href={journey.tryHref}
                  onClick={() => sendLandingEvent("hero_try_click")}
                  className="mkt-link font-medium"
                >
                  {t("h2_orTry")}
                </Link>
              )}
            </p>
          </div>
        </div>

        {/* ---------------- Build console ----------------
            The hero's product quotation: the selected workload's spec types
            itself on a prompt line, then streams the same steps the real
            planner performs. Labelled "simulated" on the chrome; the CTA at
            the bottom drops the spec into the on-page live studio. */}
        <figure className="mkt-card mkt-card--raised overflow-hidden p-0" data-testid="hero-build-console">
          <div className="flex items-center gap-2 border-b px-3 py-2" style={{ borderColor: "var(--mkt-line)" }}>
            <span className="flex gap-1" aria-hidden="true">
              <span className="size-2 rounded-full" style={{ background: "var(--mkt-line-strong)" }} />
              <span className="size-2 rounded-full" style={{ background: "var(--mkt-line-strong)" }} />
              <span className="size-2 rounded-full" style={{ background: "var(--mkt-line-strong)" }} />
            </span>
            <span className="mkt-ui-label mkt-ink-3 truncate">vegaduta · {t("h2_termTitle")}</span>
            <span className="mkt-pill ms-auto shrink-0">{t("h2_termSimLabel")}</span>
          </div>
          <BuildConsole
            workloadId={persona}
            brief={t(`h2_w_${persona}_brief`)}
            reduced={reduced}
            runLabel={t("h2_termRun")}
            onRunSpec={runSpec}
          />
          <p className="sr-only">{t("h2_termAria")}</p>
          <figcaption
            className="mkt-caption mkt-ink-2 flex flex-wrap items-center gap-x-3 gap-y-2 border-t px-4 py-3"
            style={{ borderColor: "var(--mkt-line)" }}
          >
            <span>{t("h2_termCaption")}</span>
            <button
              type="button"
              onClick={openDialog}
              className="mkt-link ms-auto inline-flex shrink-0 items-center gap-1.5 border-0 bg-transparent p-0 font-medium shadow-none"
              data-testid="hero-video-open"
            >
              <Play className="size-3.5" aria-hidden="true" />
              {t("h2_watchDemo")}
            </button>
          </figcaption>
        </figure>
      </div>

      {/* Capability marquee - code-counted facts and shipped capabilities,
          in motion. Pauses on hover; a scrollable row under reduced motion. */}
      <div
        className="mkt-marquee mt-10 border-t pt-5"
        style={{ borderColor: "var(--mkt-line)" }}
        data-testid="hero-marquee"
        data-paused={marqueePaused ? "true" : undefined}
      >
        <button
          type="button"
          onClick={() => setMarqueePaused((p) => !p)}
          className="absolute end-0 top-1 inline-flex size-7 items-center justify-center rounded-full border-0 bg-transparent p-0 shadow-none"
          style={{ color: "var(--mkt-ink-3)" }}
          aria-label={marqueePaused ? t("h2_marqueePlay") : t("h2_marqueePause")}
        >
          {marqueePaused ? (
            <Play className="size-3.5" aria-hidden="true" />
          ) : (
            <Pause className="size-3.5" aria-hidden="true" />
          )}
        </button>
        <div className="mkt-marquee__track" style={{ "--mkt-marquee-duration": "58s" } as CSSProperties}>
          {[0, 1].map((copy) => (
            <ul key={copy} className="flex items-center gap-10" aria-hidden={copy === 1 || undefined}>
              {MARQUEE_KEYS.map((k) => (
                <li
                  key={k}
                  className="mkt-small flex shrink-0 items-center gap-2 whitespace-nowrap"
                  style={{ color: "var(--mkt-ink-2)" }}
                >
                  {k === "h2_fact5" ? (
                    <ShieldCheck
                      className="size-4 shrink-0"
                      style={{ color: "var(--mkt-positive)" }}
                      aria-hidden="true"
                    />
                  ) : (
                    <Check className="size-4 shrink-0" style={{ color: "var(--mkt-accent)" }} aria-hidden="true" />
                  )}
                  <span>
                    {k === "h3_tools"
                      ? t(k, { count: PLATFORM_FACTS.builtInToolsFloor })
                      : t(FREE_MODE && k === "h2_fact5" ? "h2Fact5FreeMode" : k)}
                  </span>
                </li>
              ))}
            </ul>
          ))}
        </div>
      </div>

      {/* Full-size walkthrough with captions (native <dialog>) */}
      <dialog
        ref={dialogRef}
        onClose={closeDialog}
        className="mkt-card mkt-card--raised w-[min(96vw,1100px)] max-w-none overflow-hidden p-0 backdrop:bg-black/70"
        aria-label={t("h2_videoAria")}
      >
        <div
          className="flex items-center justify-between border-b px-4 py-2"
          style={{ borderColor: "var(--mkt-line)" }}
        >
          <span className="mkt-ui-label">
            {t("h2_videoTitle")} · {t("h2_videoSimLabel")}
          </span>
          <button
            type="button"
            onClick={closeDialog}
            className="inline-flex size-8 items-center justify-center rounded-full border-0 bg-transparent p-0 shadow-none"
            aria-label={t("h2_videoClose")}
          >
            <X className="size-4" aria-hidden="true" />
          </button>
        </div>
        <div className="aspect-video bg-black">
          <video
            ref={dialogVideoRef}
            className="h-full w-full"
            controls
            playsInline
            preload="none"
            poster={VIDEO_POSTER}
          >
            <source src={VIDEO_WEBM} type="video/webm" />
            <source src={VIDEO_MP4} type="video/mp4" />
          </video>
        </div>
      </dialog>
    </div>
  );
}
