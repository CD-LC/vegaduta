"use client";

// HeroOutcome — the landing hero, rebuilt for conversion (2026-09-17).
//
// WHY THIS REPLACES HeroUniversalAgent AS THE MOUNTED HERO. The funnel
// read-out (web-admin /funnel, Redis counters, 124 landing views) showed:
//   - 36% of visitors clicked "Sign in" from the nav — they are existing
//     users, not prospects. Of the ~79 real prospects, 64 held the hero
//     for a second and 19 reached the band under it. Two thirds left
//     INSIDE the hero.
//   - The hero measured ~3 screens tall (h1 + spark badge + sub-lead +
//     console simulation + register card + four spec plates). The h1 led
//     with a feature count ("9 channels…") and the sub-lead with SDLC / MCP
//     / tool counts — developer words on a page written for shop owners,
//     and shop words for developers. Nothing on the first screen SHOWED
//     the product: the only visual was a hand-built console mock with
//     11px text.
//   - "Watch a 60-second demo" scrolled to Magic Studio, which is a form.
//     A visitor who clicked expecting a video got a text box.
// Reach data says WHERE attention stopped, never why (see the funnel
// screen's own caveat); the three hypotheses above are what this rebuild
// tests. Event names are unchanged wherever the intent is unchanged
// (hero_signup_click, hero_try_click, hero_watch_click, hero_keep_agent_
// click) so the before/after can be read on one chart.
//
// WHAT IS HERE INSTEAD, in the order the eye meets it:
//   1. One outcome-led headline, no counts, no jargon.
//   2. A persona row (kirana / clinic / coaching / salon / developer):
//      one tap swaps an EXAMPLE BRIEF and three outcomes, so the page
//      commits to the reader instead of to everyone. The chip's persona id
//      is the exact DemoPersona wire value /try accepts, and the example
//      card's link carries it (`/try?persona=<id>`) so the sandbox skips
//      its own picker — the landing choice becomes the sandbox's seed.
//   3. An email starter: type an address, land on /signup with it filled
//      and the intro step skipped. A typed email is a micro-commitment
//      that a button click is not, and it removes one screen and one
//      field from the form. `hero_email_start` counts it.
//   4. The real 60-second walkthrough video (web/public/media/landing,
//      generated by web/scripts/landing-media — regenerable, no API keys),
//      muted-autoplay-looped in a browser frame, with a captions dialog.
//      It is labelled "simulated data" on the frame itself, and the
//      caption says where the real thing runs.
//   5. A five-fact trust strip — every number code-counted (same source
//      as PlatformLedger); "free until 1 January 2027" is the offer.
//
// 2026-09-22 AUDIENCE PIVOT — the hero now sells to the BUILDER, not the
// shop floor. Direction from the owner: salon/clinic-style SMBs are not the
// people who adopt a platform like this unprompted; the visitors who convert
// are technical — developers, founders, IT/ops — and the hero should read
// like it. So, same skeleton, new payload:
//   - The persona chips are now WORKLOAD chips (support copilot, on-call
//     triage, PR reviewer, anomaly digest, voice front desk). They no longer
//     seed /try personas — none of the DemoPersona wire values describe a
//     technical workload — they drive the console instead.
//   - The inline video yields the right column to a simulated BUILD CONSOLE
//     (.mkt-term): it types the selected spec and streams the same pipeline
//     Magic Studio actually runs — intent parse, live MCP-registry hits,
//     model pick with failover, guardrails, channel binds. The walkthrough
//     video still ships, one click away in the same dialog as before.
//   - The console's last line is the conversion seam: "run this spec" hands
//     the exact sentence to the live studio on this page via magicPrefill
//     (sessionStorage + window event — see components/try/magicPrefill.ts),
//     so what the visitor watched compile is what lands in the prompt box.
//   Beacon names are unchanged wherever the intent is unchanged
//   (hero_persona_click, hero_try_click, hero_watch_click, hero_email_start,
//   hero_keep_agent_click) so the before/after still reads on one chart.
//
// HeroUniversalAgent.tsx stays in the repo, unmounted, with every key and
// beacon name intact — same convention as the seven bands unmounted on
// 2026-09-12: the mount is one line, and the file is the record.
//
// Honesty ledger for every claim on this screen (re-verify before editing):
//   9 channels          -> core ChannelType enum (9 values)
//   22 Indian languages -> the console's language list + Sarvam/Indic TTS
//   40+ built-in tools  -> PLATFORM_FACTS.builtInToolsFloor (46-48 by the
//                          three counting rules; published as a floor)
//   free until 2027     -> commit 1dfaeb84 (every account on Unlimited)
//   Instagram / voice   -> ChannelType INSTAGRAM / VOICE exist; agents
//                          ANSWER calls — no outbound calling is claimed.
//   sandboxed code      -> code-intel workspaces; diff before merge is real
//   UPI link            -> a payment-link tool call; agent-collected UPI is
//                          NOT claimed as settled money anywhere here.
//   build console       -> labelled "simulated" on the frame; each step
//                          mirrors a thing Magic Studio genuinely does
//                          (intent parse, MCP-registry discovery, model pool
//                          pick, guardrails, channel bind). Tool NAMES are
//                          representative — the live registry returns the
//                          real ones per prompt.
//   failover chain      -> model failover chain exists (magic_failoverChain);
//                          "×3" is representative depth, not a promise.
//   workflow engine     -> NOT "Temporal": application.yml defaults to the
//                          legacy engine in prod (GEO audit 2026-09-19).
//   sales workload      -> CRM_LEAD + BULK_EMAIL nodes, reply/bounce
//                          detection, AgentSchedule interval (bb2fafcb).
//   app / crm / versions / powered-by / SSO chips -> see ShippedBand.tsx's
//                          ledger (all live in prod, checked 2026-09-28).
//
// 2026-09-28 COPY PASS — h1/lead moved to h3_* keys: the platform now builds
// the phone app around the agent (App Studio + published apps), and the old
// lead said nothing about it. New keys rather than edited h2_* ones so the
// eight hand-translated locales fall back to the new English instead of
// keeping a stale translation of the old claim.

