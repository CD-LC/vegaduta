// One-time: download the Google Fonts faces used by the storyboard/og/hero pages into ./fonts/ and
// write ./fonts/fonts.css with local @font-face rules, so rendering is deterministic and offline.
//   node fetch-fonts.mjs
import { mkdirSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import { HERE } from "./common.mjs";

const FAMILIES = "family=Sora:wght@600;700&family=Inter:wght@400;500;600&family=Noto+Sans+Devanagari:wght@400;500;600&family=JetBrains+Mono:wght@400;500";
const CSS_URL = `https://fonts.googleapis.com/css2?${FAMILIES}&display=swap`;
const KEEP_SUBSETS = new Set(["latin", "devanagari"]);
// A modern-Chrome UA makes Google return woff2 with unicode-range subsets.
const UA = "Mozilla/5.0 (Windows NT 10.0; Win64; x64) AppleWebKit/537.36 (KHTML, like Gecko) Chrome/128.0 Safari/537.36";

const dir = join(HERE, "fonts");
mkdirSync(dir, { recursive: true });
const css = await (await fetch(CSS_URL, { headers: { "User-Agent": UA } })).text();

// Blocks look like: /* latin */ @font-face { font-family: 'Sora'; font-style: normal; font-weight: 700; src: url(...) format('woff2'); unicode-range: ...; }
const blocks = [...css.matchAll(/\/\*\s*([\w-]+)\s*\*\/\s*@font-face\s*\{([^}]*)\}/g)];
let out = "/* Generated by fetch-fonts.mjs — local copies of Google Fonts faces (OFL licensed). */\n";
let n = 0;
for (const [, subset, body] of blocks) {
  if (!KEEP_SUBSETS.has(subset)) continue;
  const family = body.match(/font-family:\s*'([^']+)'/)[1];
  const weight = body.match(/font-weight:\s*(\d+)/)[1];
  const url = body.match(/url\(([^)]+)\)/)[1];
  const file = `${family.replace(/\s+/g, "")}-${weight}-${subset}.woff2`;
  const buf = Buffer.from(await (await fetch(url, { headers: { "User-Agent": UA } })).arrayBuffer());
  writeFileSync(join(dir, file), buf);
  out += `/* ${subset} */\n@font-face{${body.replace(/url\([^)]+\)/, `url(${file})`).replace(/\s+/g, " ").trim()}}\n`;
  n++;
  console.log(`${file}  ${(buf.length / 1024).toFixed(0)} KB`);
}
writeFileSync(join(dir, "fonts.css"), out);
console.log(`wrote ${n} faces to ${dir}`);
