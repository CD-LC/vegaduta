// Generates app/lib/i18n-route-namespaces.generated.ts - the per-route map of
// translation namespaces each page's module graph can reach.
//
// Why this exists (prod latency pass, 2026-09-24): the root layout serialized
// the WHOLE messages/<locale>.json into every page's RSC payload - 480 KB for
// English, ~1.4 MB for Tamil - which was ~70% of the 730 KB landing HTML and
// the single largest per-request cost on the web tier. A page only ever calls
// useTranslations("<ns>") for the namespaces in its own import closure, so the
// layout can ship just those (plus the layout's own) and let I18nProvider fetch
// the rest lazily, after first paint (see app/lib/i18n.tsx).
//
// The map is computed statically: for every app/**/page.tsx, walk relative
// and "@/" imports transitively and collect every `useTranslations("...")`
// literal. Dynamic `useTranslations(variable)` is not supported on purpose -
// the only such call site is I18nProvider itself.
//
// Runs from `npm run prebuild` so the checked-in file can never be stale in a
// built image; scripts/i18n-route-namespaces.test.ts guards it in `vitest`.
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const here = path.dirname(fileURLToPath(import.meta.url));
const webRoot = path.resolve(here, "..");
const appRoot = path.join(webRoot, "app");
const OUT = path.join(appRoot, "lib", "i18n-route-namespaces.generated.ts");

const EXT = [".tsx", ".ts", ".jsx", ".js"];
const SKIP = /\.(test|spec)\.[tj]sx?$/;

const files = new Map();
(function walk(dir) {
  for (const entry of fs.readdirSync(dir, { withFileTypes: true })) {
    const p = path.join(dir, entry.name);
    if (entry.isDirectory()) {
      if (entry.name === "node_modules") continue;
      walk(p);
    } else if (EXT.includes(path.extname(entry.name)) && !SKIP.test(entry.name)) {
      files.set(p.split(path.sep).join("/"), fs.readFileSync(p, "utf8"));
    }
  }
})(appRoot);

function resolveImport(from, spec) {
  let base;
  if (spec.startsWith("@/")) base = path.join(webRoot, spec.slice(2));
  else if (spec.startsWith(".")) base = path.resolve(path.dirname(from), spec);
  else return null;
  base = base.split(path.sep).join("/");
  const candidates = [base, ...EXT.map((e) => base + e), ...EXT.map((e) => base + "/index" + e)];
  return candidates.find((c) => files.has(c)) || null;
}

const IMPORT_RE =
  /(?:import|export)\s[^;]*?from\s+["']([^"']+)["']|import\(\s*["']([^"']+)["']\s*\)|require\(\s*["']([^"']+)["']\s*\)/g;
const NS_RE = /useTranslations\(\s*["']([\w.-]+)["']/g;

const deps = new Map();
const own = new Map();
for (const [p, src] of files) {
  const d = new Set();
  for (const m of src.matchAll(IMPORT_RE)) {
    const r = resolveImport(p, m[1] || m[2] || m[3]);
    if (r) d.add(r);
  }
  deps.set(p, d);
  own.set(p, new Set([...src.matchAll(NS_RE)].map((m) => m[1])));
}

function namespacesReachableFrom(start) {
  const seen = new Set();
  const stack = [start];
  const out = new Set();
  while (stack.length) {
    const x = stack.pop();
    if (seen.has(x)) continue;
    seen.add(x);
    for (const ns of own.get(x) || []) out.add(ns);
    for (const d of deps.get(x) || []) stack.push(d);
  }
  return out;
}

const layoutFile = path.join(appRoot, "layout.tsx").split(path.sep).join("/");
const layout = namespacesReachableFrom(layoutFile);

const routes = {};
for (const p of files.keys()) {
  if (!/\/page\.(tsx|jsx|js|ts)$/.test(p)) continue;
  const rel = path.posix.dirname(path.posix.relative(appRoot.split(path.sep).join("/"), p));
  // Route groups "(name)" and parallel/intercepting segments are not used by
  // this app today; strip groups anyway so a future one doesn't break matching.
  const route = "/" + rel.split("/").filter((s) => s !== "." && !/^\(.*\)$/.test(s)).join("/");
  const extra = [...namespacesReachableFrom(p)].filter((ns) => !layout.has(ns)).sort();
  routes[route === "//" ? "/" : route] = extra;
}

const sortedRoutes = Object.fromEntries(Object.keys(routes).sort().map((k) => [k, routes[k]]));
const body = `// GENERATED by scripts/i18n-route-namespaces.mjs - do not edit by hand.
// Regenerate with: node scripts/i18n-route-namespaces.mjs   (also runs in prebuild)
//
// LAYOUT_NAMESPACES: namespaces reachable from app/layout.tsx's module graph
// (shared chrome - shipped on every route).
// ROUTE_NAMESPACES: per page route, the additional namespaces its own module
// graph reaches. Dynamic segments keep their [param] spelling; see
// app/lib/i18n-namespaces.ts for matching.
export const LAYOUT_NAMESPACES: readonly string[] = ${JSON.stringify([...layout].sort())};

export const ROUTE_NAMESPACES: Readonly<Record<string, readonly string[]>> = ${JSON.stringify(sortedRoutes, null, 2)};
`;

if (process.argv.includes("--check")) {
  const current = fs.existsSync(OUT) ? fs.readFileSync(OUT, "utf8") : "";
  if (current !== body) {
    console.error(`${path.relative(webRoot, OUT)} is stale - run: node scripts/i18n-route-namespaces.mjs`);
    process.exit(1);
  }
  console.log("i18n route namespaces: up to date");
} else {
  fs.writeFileSync(OUT, body);
  console.log(`wrote ${path.relative(webRoot, OUT)}: ${layout.size} layout namespaces, ${Object.keys(routes).length} routes`);
}
