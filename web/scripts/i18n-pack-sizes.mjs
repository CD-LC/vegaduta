// Generates app/lib/i18n-pack-sizes.generated.ts - the on-demand download size
// of each non-English locale's catalog, for the personal-edition language-pack
// consent prompt (see app/components/LanguageSwitcher.tsx + app/lib/langPacks.ts).
//
// The number shown is what /api/i18n/<locale> actually returns: the locale
// file minus its top-level `_sourceHash` bookkeeping plus the English fallback
// bundle the provider merges against (the route returns both; English is what
// untranslated keys resolve to). Rounded up to a tenth of a megabyte - a
// consent prompt promises an order of magnitude, not bytes.
//
// Runs from `npm run prebuild` (same slot as i18n-route-namespaces.mjs) so the
// checked-in file can never go stale against messages/*.json.
import fs from "node:fs";
import path from "node:path";

const MESSAGES_DIR = path.resolve(import.meta.dirname, "../messages");
const OUT = path.resolve(import.meta.dirname, "../app/lib/i18n-pack-sizes.generated.ts");

const files = fs.readdirSync(MESSAGES_DIR).filter((f) => f.endsWith(".json") && f !== "i18n-parity-baseline.json");
const sizes = {};
for (const f of files) {
  const locale = f.replace(/\.json$/, "");
  const raw = JSON.parse(fs.readFileSync(path.join(MESSAGES_DIR, f), "utf8"));
  const { _sourceHash, ...catalog } = raw;
  // Megabytes, one decimal, always rounded UP (a promise of "about this much"
  // must never understate).
  sizes[locale] = Math.ceil((JSON.stringify(catalog).length / 1e6) * 10) / 10;
}

const body = `// GENERATED by scripts/i18n-pack-sizes.mjs - do not edit by hand.
// Regenerate with: node scripts/i18n-pack-sizes.mjs   (also runs in prebuild)
//
// Approximate download size (MB, rounded up) of each locale's on-demand pack:
// messages/<locale>.json minus _sourceHash, i.e. what /api/i18n/<locale>
// returns. en is included for completeness - it is the always-present
// fallback, never a download.
export const PACK_SIZES_MB: Readonly<Record<string, number>> = ${JSON.stringify(sizes, null, 2)};
`;
fs.writeFileSync(OUT, body, "utf8");
console.log(`wrote ${path.relative(process.cwd(), OUT)} (${files.length} locales)`);
