import { chromium } from '@playwright/test';
const D = '127.0.0.1.nip.io';
const origins = [`http://app.${D}`,`http://auth.${D}`,`http://api.${D}`,'http://localhost:8280'].join(',');
const browser = await chromium.launch({ args: [`--unsafely-treat-insecure-origin-as-secure=${origins}`] });
const ctx = await browser.newContext();
await ctx.addInitScript(() => { try { localStorage.setItem('pageGuideSeen','[]'); localStorage.setItem('vd_tour_status','skipped'); } catch {} });
const page = await ctx.newPage();
let token = '';
page.on('request', r => { const a = r.headers()['authorization']; if (a && !token && r.url().includes('/api/')) token = a.replace(/^Bearer /,''); });
await page.goto(`http://app.${D}/login`);
await page.getByLabel(/email/i).fill('a2atest@example.org');
await page.getByRole('button', { name: /continue to secure/i }).click();
await page.locator('#password').fill('TestPassw0rd!x');
await page.locator('#kc-login').click();
await page.waitForURL(u => u.hostname.startsWith('app.'), { timeout: 45000 });
await page.goto(`http://app.${D}/jobs`, { waitUntil: 'domcontentloaded' });
await page.waitForFunction(() => document.title !== '' , {timeout:15000}).catch(()=>{});
for (let i=0;i<180 && !token;i++) await page.waitForTimeout(500);
console.log('TOKEN=' + token);
await browser.close();
