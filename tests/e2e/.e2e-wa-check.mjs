import { chromium } from '@playwright/test';
const APP = 'http://app.127.0.0.1.nip.io';
const browser = await chromium.launch({ args: [`--unsafely-treat-insecure-origin-as-secure=${APP},http://auth.127.0.0.1.nip.io,http://localhost:8280`] });
const ctx = await browser.newContext();
await ctx.addInitScript(() => { try { for (const k of ['pageGuideSeen','vd_tour_status']) localStorage.setItem(k, k==='pageGuideSeen'?'[]':'skipped'); } catch {} });
const page = await ctx.newPage();
await page.goto(`${APP}/login`);
await page.getByLabel(/email/i).fill('a2atest@example.org');
await page.getByRole('button', { name: /continue to secure/i }).click();
await page.locator('#password').fill('TestPassw0rd!x');
await page.locator('#kc-login').click();
await page.waitForURL(u => u.hostname.startsWith('app.'), { timeout: 60000 });
await page.locator('header').first().waitFor({ timeout: 60000 });
await page.goto(`${APP}/admin/channels`, { waitUntil: 'domcontentloaded' }).catch(()=>{});
await page.locator('header').first().waitFor({ timeout: 90000 });
const card = page.locator('[data-testid="channel-card"][data-channel="whatsapp"]');
await card.waitFor({ timeout: 30000 });
console.log('whatsapp card visible:', await card.isVisible());
console.log('aria-pressed:', await card.getAttribute('aria-pressed'));
console.log('+connect text:', await card.getByText('+ connect').isVisible().catch(()=>false));
await card.click().catch(()=>{});
await page.waitForTimeout(1500);
console.log('Connect WhatsApp heading:', await page.getByRole('heading', { name: 'Connect WhatsApp' }).isVisible().catch(()=>false));
console.log('Meta Cloud API tab:', await page.getByRole('tab', { name: 'Meta Cloud API' }).isVisible().catch(()=>false));
console.log('Twilio tab:', await page.getByRole('tab', { name: 'Twilio' }).isVisible().catch(()=>false));
await page.screenshot({ path: '/tmp/vd-e2e/logs-E/wa-channels.png' });
await browser.close();
