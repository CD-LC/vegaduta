// Tests for the SDK generators, run against a tiny hand-written spec (fixture-openapi.json).
// Run with: node --test sdk/test/*.test.mjs
import assert from "node:assert/strict";
import { spawnSync } from "node:child_process";
import { cpSync, mkdirSync, mkdtempSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import { dirname, join } from "node:path";
import { test } from "node:test";
import { fileURLToPath } from "node:url";

import { generate } from "../generate.mjs";
import { buildModel, resolveRef } from "../lib/model.mjs";
import { camel, pascal, snake, typeName, uniqueName, words } from "../lib/names.mjs";

const here = dirname(fileURLToPath(import.meta.url));
const spec = JSON.parse(readFileSync(join(here, "fixture-openapi.json"), "utf8"));
const files = generate(spec);

test("generate returns the generated files, each with a DO NOT EDIT banner", () => {
  assert.deepEqual(Object.keys(files).sort(), [
    "python/vegaduta_sdk/generated/__init__.py",
    "python/vegaduta_sdk/generated/client.py",
    "python/vegaduta_sdk/generated/models.py",
    "typescript/src/generated/client.ts",
    "typescript/src/generated/types.ts",
  ]);
  for (const content of Object.values(files)) {
    assert.match(content, /DO NOT EDIT\. Generated by sdk\/generate\.mjs/);
  }
});

test("generation is deterministic", () => {
  assert.deepEqual(generate(spec), files);
});

test("names helpers", () => {
  assert.deepEqual(words("X-Trace"), ["x", "trace"]);
  assert.deepEqual(words("HTTPServer"), ["http", "server"]);
  assert.equal(camel("widgetId"), "widgetId");
  assert.equal(camel("X-Trace"), "xTrace");
  assert.equal(pascal("developer api"), "DeveloperApi");
  assert.equal(snake("uploadImage"), "upload_image");
  assert.equal(typeName("Outer.Inner-x"), "Outer_Inner_x");
  const used = new Set(["a"]);
  assert.equal(uniqueName("a", used), "a2");
  assert.equal(uniqueName("a", used), "a3");
});

test("model: tags, method names and reserved words", () => {
  const model = buildModel(spec);
  assert.deepEqual(
    model.groups.map((g) => [g.tag, g.tsProp, g.className]),
    [
      ["Health", "health", "HealthApi"],
      ["Widget", "widget", "WidgetApi"],
    ],
  );
  const health = model.groups[0].operations[0];
  assert.equal(health.tsName, "import"); // legal as a method name
  assert.equal(health.pyName, "import_"); // keyword in Python
  const widget = model.groups[1].operations.map((o) => o.tsName);
  assert.deepEqual(widget, ["list", "create", "get", "delete", "events", "uploadImage", "setNote"]);
  assert.equal(model.typeNames.get("Error"), "ErrorBody");
});

test("resolveRef follows local pointers and rejects unknown ones", () => {
  assert.equal(resolveRef(spec, "#/components/schemas/Kind").enum.length, 2);
  assert.throws(() => resolveRef(spec, "#/components/schemas/Nope"), /unresolved/);
  assert.throws(() => resolveRef(spec, "http://example.com/x"), /unsupported/);
});

test("types.ts: interfaces, enums, optionality and quoting", () => {
  const t = files["typescript/src/generated/types.ts"];
  assert.ok(t.includes("export interface CreateWidget {\n  name: string;\n  quantity?: number;\n  note_text?: string;\n}"), t);
  assert.ok(
    t.includes(
      "export interface ErrorBody {\n  [key: string]: unknown;\n  timestamp?: string;\n  status: number;\n  error: string;\n  code?: string;\n}",
    ),
    t,
  );
  assert.ok(t.includes('export type Kind = "SMALL" | "LARGE";'));
  assert.ok(t.includes('"a-b"?: string;'));
  assert.ok(t.includes("export interface Widget {"));
  // required + default (a Java primitive) is optional on input; a plain required field stays required
  assert.ok(t.includes("\n  count?: number;\n"));
  assert.ok(t.includes("\n  name: string;\n"));
  assert.ok(t.includes("\n  tags?: string[];\n"));
  assert.ok(t.includes("\n  kind?: Kind;\n"));
  assert.ok(t.includes("\n  parent?: Widget;\n")); // cycle through $ref
  assert.ok(t.includes("\n  extra?: Record<string, number>;\n"));
  assert.ok(t.trimEnd().endsWith("export {};"));
});

test("client.ts: one class per tag with typed methods", () => {
  const c = files["typescript/src/generated/client.ts"];
  assert.ok(c.includes('import type * as T from "./types";'));
  assert.ok(c.includes("export class HealthApi {"));
  assert.ok(c.includes("export class WidgetApi {"));
  assert.ok(c.includes("  import(options?: CallOptions): Promise<Record<string, unknown>> {"));
  assert.ok(
    c.includes(
      "  list(options?: CallOptions<{ limit?: number; kind?: T.Kind }, HeaderParams>): Promise<T.Widget[]> {",
    ),
    c,
  );
  assert.ok(c.includes("  create(body: T.CreateWidget, options?: CallOptions): Promise<T.Widget> {"));
  assert.ok(
    c.includes('return this.http.request<T.Widget>({ ...options, method: "POST", path: "/api/widgets", body });'),
    c,
  );
  assert.ok(
    c.includes(
      '  get(widgetId: string, options: CallOptions<QueryParams, { "X-Trace": string }> & { headers: { "X-Trace": string } }): Promise<T.Widget> {',
    ),
    c,
  );
  assert.ok(c.includes("path: `/api/widgets/${encodeURIComponent(String(widgetId))}`"));
  assert.ok(c.includes("  delete(widgetId: string, options?: CallOptions): Promise<void> {"));
  assert.ok(c.includes('response: "void"'));
  assert.ok(c.includes("  events(widgetId: string, options?: CallOptions): AsyncGenerator<string, void, undefined> {"));
  assert.ok(c.includes("return this.http.stream({ ...options, method: \"GET\""));
  assert.ok(c.includes("  uploadImage(widgetId: string, body: FormData, options?: CallOptions): Promise<Blob> {"));
  assert.ok(c.includes('bodyType: "multipart"'));
  assert.ok(c.includes('response: "blob"'));
  assert.ok(c.includes("  setNote(widgetId: string, body?: string, options?: CallOptions): Promise<string> {"));
  assert.ok(c.includes('bodyType: "text", contentType: "text/plain", response: "text"'));
  assert.ok(c.includes("`GET /api/widgets`"));
  assert.ok(c.includes("  readonly health: HealthApi;\n  readonly widget: WidgetApi;"));
  assert.ok(c.includes("    this.widget = new WidgetApi(this.http);"));
});

test("models.py: Literal aliases and TypedDicts (class and functional forms)", () => {
  const m = files["python/vegaduta_sdk/generated/models.py"];
  assert.ok(m.includes("from __future__ import annotations"));
  assert.ok(m.includes('Kind = Literal["SMALL", "LARGE"]'));
  assert.ok(
    m.includes(
      "class _CreateWidgetRequired(TypedDict):\n    name: str\n\n\nclass CreateWidget(_CreateWidgetRequired, total=False):\n    quantity: int\n    note_text: str\n",
    ),
    m,
  );
  assert.ok(m.includes('class ErrorBody(_ErrorBodyRequired, total=False):\n    """Standard error body."""\n'));
  assert.ok(m.includes('Odd = TypedDict("Odd", {"a-b": "str", "from": "int"}, total=False)'));
  assert.ok(
    m.includes(
      "class Widget(_WidgetRequired, total=False):\n    id: str\n    count: int\n    tags: List[str]\n    kind: Kind\n    parent: Widget\n    extra: Dict[str, float]\n",
    ),
    m,
  );
});

test("client.py: typed methods, keyword-only params and SSE", () => {
  const c = files["python/vegaduta_sdk/generated/client.py"];
  assert.ok(c.includes("from . import models as m"));
  assert.ok(c.includes("class HealthApi:"));
  assert.ok(c.includes("    def import_(self) -> Dict[str, Any]:"));
  assert.ok(
    c.includes("    def list(self, *, limit: Optional[int] = None, kind: Optional[m.Kind] = None) -> List[m.Widget]:"),
    c,
  );
  assert.ok(c.includes('return self._http.request("GET", "/api/widgets", query={"limit": limit, "kind": kind})'));
  assert.ok(c.includes("    def create(self, body: m.CreateWidget) -> m.Widget:"));
  assert.ok(c.includes('return self._http.request("POST", "/api/widgets", body=body)'));
  assert.ok(c.includes("    def get(self, widget_id: str, *, x_trace: str) -> m.Widget:"));
  assert.ok(
    c.includes('return self._http.request("GET", f"/api/widgets/{quote_path(widget_id)}", headers={"X-Trace": x_trace})'),
    c,
  );
  assert.ok(c.includes("    def delete(self, widget_id: str) -> None:"));
  assert.ok(c.includes('response="void"'));
  assert.ok(c.includes("    def events(self, widget_id: str) -> Iterator[str]:"));
  assert.ok(c.includes('return self._http.stream("GET", f"/api/widgets/{quote_path(widget_id)}/events")'));
  assert.ok(c.includes("    def upload_image(self, widget_id: str, body: Dict[str, Any]) -> bytes:"));
  assert.ok(c.includes('body_type="multipart"'));
  assert.ok(c.includes("    def set_note(self, widget_id: str, body: Optional[str] = None) -> str:"));
  assert.ok(c.includes('body_type="text", content_type="text/plain", response="text"'));
  assert.ok(c.includes("class VegadutaClient:"));
  assert.ok(c.includes("        self.widget = WidgetApi(self.http)"));
  assert.ok(c.trimEnd().endsWith("Client = VegadutaClient"));
});

