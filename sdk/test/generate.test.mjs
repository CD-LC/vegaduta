// Optional end-to-end check: write the generated Python next to the real runtime in a temp dir and
// import it with a real interpreter. Skipped when no Python 3.9+ is installed.

function findPython() {
  for (const cmd of ["python3", "python", "py"]) {
    const r = spawnSync(cmd, ["--version"], { encoding: "utf8" });
    if (r.status === 0) {
      const m = /Python 3\.(\d+)/.exec(`${r.stdout}${r.stderr}`);
      if (m && Number(m[1]) >= 9) return cmd;
    }
  }
  return null;
}

test("generated Python imports and instantiates with a real interpreter", (t) => {
  const python = findPython();
  if (!python) {
    t.skip("no Python 3.9+ on PATH");
    return;
  }
  const tmp = mkdtempSync(join(tmpdir(), "vegaduta-sdk-test-"));
  try {
    const pkg = join(tmp, "vegaduta_sdk");
    mkdirSync(pkg, { recursive: true });
    for (const name of ["__init__.py", "runtime.py"]) {
      cpSync(join(here, "..", "python", "vegaduta_sdk", name), join(pkg, name));
    }
    const gen = join(pkg, "generated");
    mkdirSync(gen, { recursive: true });
    for (const name of ["__init__.py", "models.py", "client.py"]) {
      writeFileSync(join(gen, name), files[`python/vegaduta_sdk/generated/${name}`], "utf8");
    }
    const code = [
      "import vegaduta_sdk as s",
      "c = s.VegadutaClient(token='t', base_url='http://127.0.0.1:1')",
      "assert callable(c.widget.list) and callable(c.health.import_)",
      "assert s.models.Kind is not None",
      "print('ok')",
    ].join("\n");
    const r = spawnSync(python, ["-c", code], {
      cwd: tmp,
      env: { ...process.env, PYTHONPATH: tmp },
      encoding: "utf8",
    });
    assert.equal(r.status, 0, `${r.stdout}\n${r.stderr}`);
    assert.match(r.stdout, /ok/);
  } finally {
    rmSync(tmp, { recursive: true, force: true });
  }
});
