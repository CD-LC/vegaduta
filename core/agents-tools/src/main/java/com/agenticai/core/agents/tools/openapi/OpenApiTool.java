package com.agenticai.core.agents.tools.openapi;

import jakarta.persistence.Column;
import jakarta.persistence.Entity;
import jakarta.persistence.EnumType;
import jakarta.persistence.Enumerated;
import jakarta.persistence.FetchType;
import jakarta.persistence.GeneratedValue;
import jakarta.persistence.GenerationType;
import jakarta.persistence.Id;
import jakarta.persistence.JoinColumn;
import jakarta.persistence.ManyToOne;
import jakarta.persistence.Table;
import jakarta.persistence.UniqueConstraint;
import java.time.Instant;
import java.util.UUID;

/**
 * One operation of an imported {@link OpenApiToolSource}, materialised as a tool an agent can call.
 * Everything the LLM sees ({@code toolName}, {@code summary}/{@code description}, {@code
 * inputSchemaJson}) and everything the executor needs to turn a tool input back into an HTTP
 * request ({@code parametersJson}, {@code bodyMode}, {@code httpMethod}, {@code pathTemplate}) is
 * generated by {@link OpenApiSpecParser} at import and refresh time - nothing here is authored by
 * hand.
 *
 * <p>{@code operationKey} ({@code "METHOD /path"}) is the identity that survives a refresh: {@code
 * operationId} is optional in the spec and gets renamed, but a method+path is what the API actually
 * serves.
 */
@com.agenticai.core.security.TenantConfigEntity
@Entity
@Table(
        name = "openapi_tool",
        uniqueConstraints = {
            @UniqueConstraint(columnNames = "tool_name"),
            @UniqueConstraint(columnNames = {"source_id", "operation_key"})
        })
public class OpenApiTool {

    @Id
    @GeneratedValue(strategy = GenerationType.UUID)
    private UUID id;

    // EAGER on purpose: OpenApiToolCallback#call runs later, on Spring AI's
    // streaming thread with no open session, and needs the source's baseUrl
    // and auth settings then. A LAZY proxy there would be a
    // LazyInitializationException on the first real tool call.
    @ManyToOne(fetch = FetchType.EAGER, optional = false)
    @JoinColumn(name = "source_id", nullable = false)
    private OpenApiToolSource source;

    @Column(name = "tool_name", nullable = false, length = 64)
    private String toolName;

    @Column(name = "operation_key", nullable = false, length = 600)
    private String operationKey;

    @Column(name = "operation_id", length = 256)
    private String operationId;

    @Column(name = "http_method", nullable = false, length = 12)
    private String httpMethod;

    @Column(name = "path_template", nullable = false, columnDefinition = "TEXT")
    private String pathTemplate;

    @Column(columnDefinition = "TEXT")
    private String summary;

    @Column(columnDefinition = "TEXT")
    private String description;

    @Column(name = "parameters_json", nullable = false, columnDefinition = "TEXT")
    private String parametersJson;

    @Enumerated(EnumType.STRING)
    @Column(name = "body_mode", nullable = false, length = 16)
    private OpenApiBodyMode bodyMode;

    @Column(name = "body_content_type", length = 128)
    private String bodyContentType;

    @Column(name = "input_schema_json", nullable = false, columnDefinition = "TEXT")
    private String inputSchemaJson;

    @Column(nullable = false)
    private boolean enabled;

    @Column(nullable = false)
    private boolean deprecated;

    @Column(name = "created_at", nullable = false, updatable = false)
    private Instant createdAt;

    @Column(name = "updated_at", nullable = false)
    private Instant updatedAt;

    protected OpenApiTool() {
        // JPA
    }

    public OpenApiTool(
            OpenApiToolSource source,
            String toolName,
            OpenApiSpecParser.ParsedOperation op,
            boolean enabled) {
        this.source = source;
        this.toolName = toolName;
        this.enabled = enabled;
        Instant now = Instant.now();
        this.createdAt = now;
        this.updatedAt = now;
        applyOperation(op);
    }

    /**
     * Re-applies a (re)parsed operation on refresh; the tool name and enabled flag are preserved.
     */
    public void applyOperation(OpenApiSpecParser.ParsedOperation op) {
        this.operationKey = op.operationKey();
        this.operationId = op.operationId();
        this.httpMethod = op.method();
        this.pathTemplate = op.path();
        this.summary = op.summary();
        this.description = op.description();
        this.parametersJson = op.parametersJson();
        this.bodyMode = op.bodyMode();
        this.bodyContentType = op.bodyContentType();
        this.inputSchemaJson = op.inputSchemaJson();
        this.deprecated = op.deprecated();
        this.updatedAt = Instant.now();
    }

    public void setEnabled(boolean enabled) {
        this.enabled = enabled;
        this.updatedAt = Instant.now();
    }

    public UUID getId() {
        return id;
    }

    public OpenApiToolSource getSource() {
        return source;
    }

    public String getToolName() {
        return toolName;
    }

    public String getOperationKey() {
        return operationKey;
    }

    public String getOperationId() {
        return operationId;
    }

    public String getHttpMethod() {
        return httpMethod;
    }

    public String getPathTemplate() {
        return pathTemplate;
    }

    public String getSummary() {
        return summary;
    }

    public String getDescription() {
        return description;
    }

    public String getParametersJson() {
        return parametersJson;
    }

    public OpenApiBodyMode getBodyMode() {
        return bodyMode;
    }

    public String getBodyContentType() {
        return bodyContentType;
    }

    public String getInputSchemaJson() {
        return inputSchemaJson;
    }

    public boolean isEnabled() {
        return enabled;
    }

    public boolean isDeprecated() {
        return deprecated;
    }

    public Instant getCreatedAt() {
        return createdAt;
    }

    public Instant getUpdatedAt() {
        return updatedAt;
    }
}
