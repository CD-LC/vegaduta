    private static ReasoningDepth parseDepth(String raw, List<String> warnings) {
        if (raw == null || raw.isBlank()) {
            return ReasoningDepth.FAST;
        }
        try {
            return ReasoningDepth.valueOf(raw.toUpperCase(Locale.ROOT));
        } catch (IllegalArgumentException e) {
            warnings.add("Unknown reasoning depth '" + raw + "'; used FAST.");
            return ReasoningDepth.FAST;
        }
    }

    private static String detectedLocale(JsonNode skeleton) {
        String l = text(skeleton, "locale");
        return l != null && BriefRefs.LOCALE.matcher(l).matches() ? l : "en";
    }

    private static String titleOf(JsonNode skeleton, String prompt) {
        String title = text(skeleton, "title");
        if (title == null || title.length() < 3) {
            title = truncate(prompt, 60);
        }
        title = truncate(title, 120);
        return title.length() < 3 ? "New solution" : title;
    }

    /** The schema needs goal >= 10 chars; a shorter prompt is padded rather than rewritten. */
    private static String padGoal(String prompt) {
        return prompt.length() >= 10 ? prompt : (prompt + "          ").substring(0, 10);
    }

    /**
     * The object entries of a skeleton array, capped at {@code max} (with a warning), each
     * guaranteed a unique non-blank "key" so cross-references and ref assignment stay in step.
     */
    private List<JsonNode> limited(JsonNode array, int max, String what, List<String> warnings) {
        List<JsonNode> out = new ArrayList<>();
        if (array != null && array.isArray()) {
            for (JsonNode n : array) {
                if (n.isObject()) {
                    out.add(n);
                }
            }
        }
        if (out.size() > max) {
            warnings.add(
                    "The plan proposed "
                            + out.size()
                            + " "
                            + what
                            + "; only the first "
                            + max
                            + " were kept.");
            out = new ArrayList<>(out.subList(0, max));
        }
        Set<String> seen = new LinkedHashSet<>();
        for (int i = 0; i < out.size(); i++) {
            String key = text(out.get(i), "key");
            if (key == null || !seen.add(key)) {
                key = "auto-" + what.replace(' ', '-') + "-" + i;
                seen.add(key);
                ((ObjectNode) out.get(i)).put("key", key);
            }
        }
        return out;
    }
