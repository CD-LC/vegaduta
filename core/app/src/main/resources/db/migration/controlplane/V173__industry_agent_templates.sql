-- public gallery immediately with no moderation step. config_json is a
-- serialised AgentSnapshot (see TemplateSnapshotService) using the SAME field
-- set as V163 so an import round-trips cleanly through CommunityTemplateService.
--
-- Scope: ready-to-hire starting points for the most common Indian-SMB verticals
-- ("add community templates for various industry use cases"). Every prompt is
-- capability-honest — these are conversational, knowledge-base-grounded agents
-- the tenant briefs with their OWN documents (menu, catalogue, price list,
-- policies) via the Knowledge page. None claim a real integration (payments,
-- calendars, courier APIs, EHR/DMS) that the tenant has not connected: a
-- customer-facing agent gathers the request and hands off / asks to confirm,
-- it never fabricates that it booked/charged/shipped anything. Consequential
-- steps stay SEMI_AUTONOMOUS/SUPERVISED so a human confirms.
--
-- Category is free-form (the web gallery humanises unknown ids via
-- FALLBACK_CATEGORY, same as V163's FAQ/SUPPORT/FINANCE/RESEARCH), so the
-- vertical name is used directly for at-a-glance industry grouping.
--
-- allowedToolNames is limited to "search_knowledge_base" (the one always-safe,
-- always-present tool when knowledgeBaseEnabled) or [] — no template references
-- a tool a fresh tenant would not have. sarvamEnabled=true on the customer-
-- facing verticals for Indian-language answers; the professional/high-risk ones
-- (CA, legal) run RIGOROUS + SUPERVISED with an explicit no-advice disclaimer.

