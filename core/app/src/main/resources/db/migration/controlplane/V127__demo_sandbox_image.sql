-- AI image generation inside the "try it without registering" demo sandbox
-- (core/tenancy/demo + core/imagegen/demo).
--
-- Version note: this repo's Flyway locations merge controlplane/ and tenant/
-- into ONE shared version sequence (see application.yml's flyway comment).
-- V126 (demo_sandbox_session) is the highest taken, so this is V127.
--
-- ---------------------------------------------------------------------------
-- WHY A COUNTER **AND** A TABLE
-- ---------------------------------------------------------------------------
-- 1. `demo_session.image_count` - the hot-path abuse counter, deliberately
--    denormalised onto the session row exactly like the existing
--    `message_count` next to it. Every single POST /api/demo/image has to ask
--    "has this sandbox spent its allowance?" BEFORE it spends real money at
--    Google, and that question must be one column read on a row the request
--    has already loaded by token hash - not a COUNT(*) over a second table
--    that grows forever. Same call, same reasoning, as message_count.
--
-- 2. `control_plane.demo_generated_image` - one row per stored image. This
--    is NOT redundant with the counter, and it is not analytics garnish
--    either; it is load-bearing for how the image is SERVED:
--
--      A browser cannot send `X-Demo-Token` on an <img src>. So the demo's
--      normal "identity is a header" contract physically cannot cover the
--      image fetch. The image URL is therefore a CAPABILITY URL - the row's
--      own random UUID primary key is the credential, exactly the same
--      unguessable-identifier posture the platform already takes for a
--      workflow webhook path. That means the GET has to resolve
--      id -> object_key WITHOUT a demo token, and without knowing which
--      tenant schema to look in, which is only possible from the CONTROL
--      PLANE. Hence a control_plane table rather than reusing the per-tenant
--      `generated_image` table core/imagegen already has for authenticated
--      BYOK generations.
--
--    Falling out of that for free (rather than as the reason it exists): the
--    prompt/session/timestamp trail an operator or the analytics workstream
--    needs to answer "what are anonymous visitors actually generating, and is
--    anyone abusing it".
--
-- Bytes themselves never touch Postgres - only the S3/MinIO object key, the
-- same split GeneratedImage/SarvamGeneratedAudio already use.

ALTER TABLE control_plane.demo_session
    ADD COLUMN image_count INTEGER NOT NULL DEFAULT 0;

CREATE TABLE control_plane.demo_generated_image (
    -- Random UUID, and it is the capability credential in the public image
    -- URL (see the header note) - so it is generated by the application
    -- (Hibernate GenerationType.UUID = random v4), never a sequence, and
    -- never anything an attacker could enumerate.
    id            UUID PRIMARY KEY,
    -- The sandbox that generated it. Not an FK, matching demo_session's own
    -- deliberate no-FK stance to control_plane.tenant: a future operator-run
    -- purge of old demo sessions must not fail on a NO ACTION constraint.
    session_id    UUID         NOT NULL,
    -- S3/MinIO key under "demo-images/". The bytes live there; this table
    -- stores the pointer only.
    object_key    VARCHAR(512) NOT NULL,
    content_type  VARCHAR(128) NOT NULL,
    -- Truncated to 500 chars by the application before insert (the prompt
    -- cap itself is the `demo.image.max-prompt-length` platform setting,
    -- default 300). Kept so abuse is reviewable after the fact - an
    -- anonymous, unauthenticated free-text field that costs money per call
    -- is exactly the thing you want a readable trail of.
    prompt        TEXT         NOT NULL,
    -- Which model actually produced it, e.g. "gemini-2.5-flash-image".
    -- Recorded per row rather than assumed, because the model is a platform
    -- setting an operator can retune without a redeploy.
    model         VARCHAR(128) NOT NULL,
    -- Abuse forensics only, never shown to the visitor. Same width/reasoning
    -- as demo_session.created_ip (full IPv6 literal).
    created_ip    VARCHAR(45),
    created_at    TIMESTAMPTZ  NOT NULL
);

-- "Show me everything this sandbox generated" - the abuse-review and
-- per-session-history read. Also what a future purge job would scan.
CREATE INDEX idx_demo_generated_image_session ON control_plane.demo_generated_image (session_id);

-- Time-ordered sweep: "what did anonymous visitors generate in the last
-- hour/day", and the retention scan that will eventually reclaim the objects.
CREATE INDEX idx_demo_generated_image_created_at ON control_plane.demo_generated_image (created_at);
