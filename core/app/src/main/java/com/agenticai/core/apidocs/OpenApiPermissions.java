package com.agenticai.core.apidocs;

import java.io.BufferedReader;
import java.io.IOException;
import java.io.InputStream;
import java.io.InputStreamReader;
import java.nio.charset.StandardCharsets;
import java.util.ArrayList;
import java.util.LinkedHashMap;
import java.util.List;
import java.util.Map;
import java.util.regex.Matcher;
import java.util.regex.Pattern;
import org.springframework.util.AntPathMatcher;

/**
 * The authority each operation needs, read from {@code security/authorization-rule-snapshot.txt}:
 * the golden file {@code SecurityRuleSnapshotTest} writes from the REAL main filter chain (every
 * rule's matcher plus a grant vector over a fixed set of principals). Building that chain needs a
 * Spring context, which this generator deliberately avoids, so it reads the snapshot instead. The
 * snapshot is a test resource: the spec is only ever generated by tests ({@code
 * OpenApiSpecGeneratorTest}, {@code OpenApiSpecFreshnessTest}), whose classpath has it. Without it
 * (a main-classpath run) operations simply carry no permission extension.
 *
 * <p>Rules are matched in file order, first match wins, as Spring Security does. A rule's grant
 * vector becomes:
 *
 * <ul>
 *   <li>{@code x-permissions: {anyOf: [PERM_...]}} when single-permission principals pass and a
 *       plain member does not;
 *   <li>{@code x-permissions: {allOf: [PERM_MANAGE_AGENTS, PERM_MANAGE_WORKFLOWS_ADMIN]}} when only
 *       the combined principal passes;
 *   <li>{@code x-roles: [tenant-admin | platform-admin]} for the roles that pass on their own;
 *   <li>nothing when any authenticated member passes (the {@code security} block says enough).
 * </ul>
 */
final class OpenApiPermissions {

    static final String RESOURCE = "/security/authorization-rule-snapshot.txt";
    /** {@code PathPattern [GET /api/x/**]} (Spring Security 7's rendering; the method is optional). */
    private static final Pattern RULE =
            Pattern.compile("^PathPattern \\[(?:([A-Z]+) )?([^\\]]*)] => ([Y-]+)$");
    private static final AntPathMatcher MATCHER = new AntPathMatcher();
    private static final String MEMBER = "member";
    private static final String COMBINED = "AGENTS+WORKFLOWS_ADMIN";

    record Rule(String method, String pattern, String grants) {}

    private final List<String> principals;
    private final List<Rule> rules;

    private OpenApiPermissions(List<String> principals, List<Rule> rules) {
        this.principals = principals;
        this.rules = rules;
    }

    /** The snapshot on the classpath, or an empty instance when it is absent. */
    static OpenApiPermissions load() {
        try (InputStream in = OpenApiPermissions.class.getResourceAsStream(RESOURCE)) {
            if (in == null) {
                return new OpenApiPermissions(List.of(), List.of());
            }
            BufferedReader reader = new BufferedReader(new InputStreamReader(in, StandardCharsets.UTF_8));
            return parse(reader.lines().toList());
        } catch (IOException e) {
            return new OpenApiPermissions(List.of(), List.of());
        }
    }

    static OpenApiPermissions parse(List<String> lines) {
        List<String> principals = List.of();
        List<Rule> rules = new ArrayList<>();
        for (String line : lines) {
            if (line.startsWith("# principals: ")) {
                principals = List.of(line.substring("# principals: ".length()).split(",\\s*"));
                continue;
            }
            Matcher m = RULE.matcher(line.strip());
            if (m.matches()) {
                rules.add(new Rule(m.group(1), m.group(2), m.group(3)));
            }
        }
        return new OpenApiPermissions(principals, rules);
    }

    boolean isEmpty() {
        return rules.isEmpty();
    }

    /** The first rule matching the operation, or null (the chain's anyRequest().authenticated()). */
    Rule ruleFor(String httpMethod, String path) {
        for (Rule r : rules) {
            if (r.method() != null && !r.method().equalsIgnoreCase(httpMethod)) {
                continue;
            }
            if (MATCHER.match(r.pattern(), path)) {
                return r;
            }
        }
        return null;
    }

    /**
     * The extensions to put on the operation (possibly empty), plus a sentence for its description
     * under the key {@code "note"}.
     */
    Map<String, Object> extensionsFor(String httpMethod, String path) {
        Map<String, Object> out = new LinkedHashMap<>();
        Rule rule = ruleFor(httpMethod, path);
        if (rule == null || principals.size() != rule.grants().length() || granted(rule, MEMBER)) {
            return out;
        }
        List<Object> any = new ArrayList<>();
        List<Object> roles = new ArrayList<>();
        for (int i = 0; i < principals.size(); i++) {
            String p = principals.get(i);
            if (rule.grants().charAt(i) != 'Y') {
                continue;
            }
            if (p.startsWith("PERM_")) {
                any.add(p);
            } else if ("tenant-admin".equals(p) || "platform-admin".equals(p)) {
                roles.add(p);
            }
        }
        String note;
        if (!any.isEmpty()) {
            out.put("x-permissions", Map.of("anyOf", any));
            note = "Requires " + String.join(" or ", any.stream().map(String::valueOf).toList());
        } else if (granted(rule, COMBINED)) {
            List<Object> all = List.of("PERM_MANAGE_AGENTS", "PERM_MANAGE_WORKFLOWS_ADMIN");
            out.put("x-permissions", Map.of("allOf", all));
            note = "Requires both PERM_MANAGE_AGENTS and PERM_MANAGE_WORKFLOWS_ADMIN";
        } else if (!roles.isEmpty()) {
            note = "Restricted to " + String.join(" or ", roles.stream().map(String::valueOf).toList());
        } else {
            return out;
        }
        if (!roles.isEmpty()) {
            out.put("x-roles", roles);
            if (out.containsKey("x-permissions")) {
                note += " (or the " + String.join(" or ", roles.stream().map(String::valueOf).toList()) + " role)";
            }
        }
        out.put("note", note + ".");
        return out;
    }

    private boolean granted(Rule rule, String principal) {
        int i = principals.indexOf(principal);
        return i >= 0 && rule.grants().charAt(i) == 'Y';
    }
}
