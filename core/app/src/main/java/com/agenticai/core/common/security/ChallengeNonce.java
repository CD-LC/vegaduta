package com.agenticai.core.common.security;

import com.fasterxml.jackson.databind.JsonNode;
import jakarta.persistence.*;
import java.net.InetAddress;
import java.time.Instant;
import java.util.UUID;
import org.hibernate.annotations.JdbcTypeCode;
import org.hibernate.type.SqlTypes;

/**
 * Challenge nonce: temporary one-time-use tokens for fraud challenge verification (hCaptcha, email
 * OTP, etc.). Each nonce represents a single challenge issued to a client and is consumed when
 * verified.
 *
 * <p>Tenant-schema entity (lives in the calling tenant's Postgres schema). Persisted via migration
 * V358 ({@code challenge_nonces}, {@code db/migration/tenant}).
 */
@Entity
@Table(
        name = "challenge_nonces",
        indexes = {
            @Index(name = "idx_challenge_nonces_lookup", columnList = "tenant_id,id,expires_at"),
            @Index(name = "idx_challenge_nonces_expires", columnList = "expires_at"),
            @Index(name = "idx_challenge_nonces_verified", columnList = "tenant_id,verified_at")
        })
public class ChallengeNonce {

    /** Primary key: UUID v4 as string (generated by client/server as a token) */
    @Id
    @Column(length = 128)
    private String id;

    @Column(nullable = false)
    private UUID tenantId;

    /**
     * User ID if the challenge is for a specific authenticated user, null for unauthenticated flows
     */
    @Column private UUID userId;

    /** Client IP address that requested the challenge */
    @Column(nullable = false)
    private InetAddress clientIp;

    /** Challenge type: HCAPTCHA, EMAIL_OTP, SMS_OTP, PUSH_NOTIFICATION, etc. */
    @Column(nullable = false, length = 20)
    private String challengeType;

    /** Additional metadata (stored as JSON): reason, retry_count, etc. */
    @JdbcTypeCode(SqlTypes.JSON)
    @Column(columnDefinition = "jsonb")
    private JsonNode metadata;

    /** Timestamp when the nonce was created */
    @Column(nullable = false)
    private Instant createdAt;

    /** Timestamp when this nonce expires (it becomes unusable after this time) */
    @Column(nullable = false)
    private Instant expiresAt;

    /** Timestamp when the nonce was successfully verified (consumed) */
    @Column private Instant verifiedAt;

    /** IP address from which the verification occurred (should match clientIp for security) */
    @Column private InetAddress verifiedByIp;

    // Constructors
    public ChallengeNonce() {
        this.createdAt = Instant.now();
    }

    public ChallengeNonce(
            String id,
            UUID tenantId,
            InetAddress clientIp,
            String challengeType,
            Instant expiresAt) {
        this.id = id;
        this.tenantId = tenantId;
        this.clientIp = clientIp;
        this.challengeType = challengeType;
        this.expiresAt = expiresAt;
        this.createdAt = Instant.now();
    }

    // Getters and Setters
    public String getId() {
        return id;
    }

    public void setId(String id) {
        this.id = id;
    }

    public UUID getTenantId() {
        return tenantId;
    }

    public void setTenantId(UUID tenantId) {
        this.tenantId = tenantId;
    }

    public UUID getUserId() {
        return userId;
    }

    public void setUserId(UUID userId) {
        this.userId = userId;
    }

    public InetAddress getClientIp() {
        return clientIp;
    }

    public void setClientIp(InetAddress clientIp) {
        this.clientIp = clientIp;
    }

    public String getChallengeType() {
        return challengeType;
    }

    public void setChallengeType(String challengeType) {
        this.challengeType = challengeType;
    }

    public JsonNode getMetadata() {
        return metadata;
    }

    public void setMetadata(JsonNode metadata) {
        this.metadata = metadata;
    }

    public Instant getCreatedAt() {
        return createdAt;
    }

    public void setCreatedAt(Instant createdAt) {
        this.createdAt = createdAt;
    }

    public Instant getExpiresAt() {
        return expiresAt;
    }

    public void setExpiresAt(Instant expiresAt) {
        this.expiresAt = expiresAt;
    }

    public Instant getVerifiedAt() {
        return verifiedAt;
    }

    public void setVerifiedAt(Instant verifiedAt) {
        this.verifiedAt = verifiedAt;
    }

    public InetAddress getVerifiedByIp() {
        return verifiedByIp;
    }

    public void setVerifiedByIp(InetAddress verifiedByIp) {
        this.verifiedByIp = verifiedByIp;
    }

    public boolean isValid() {
        return Instant.now().isBefore(expiresAt) && verifiedAt == null;
    }

    public boolean isVerified() {
        return verifiedAt != null
                && Instant.now().isBefore(expiresAt.plus(java.time.Duration.ofMinutes(5)));
    }

    @Override
    public String toString() {
        return "ChallengeNonce{"
                + "id='"
                + id
                + '\''
                + ", tenantId="
                + tenantId
                + ", userId="
                + userId
                + ", clientIp="
                + clientIp
                + ", challengeType='"
                + challengeType
                + '\''
                + ", createdAt="
                + createdAt
                + ", expiresAt="
                + expiresAt
                + ", verifiedAt="
                + verifiedAt
                + '}';
    }
}
