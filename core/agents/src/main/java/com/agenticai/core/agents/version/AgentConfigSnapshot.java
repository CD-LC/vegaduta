package com.agenticai.core.agents.version;

import com.agenticai.core.agents.core.Agent;
import com.agenticai.core.agents.core.AgentAutonomyTier;
import com.agenticai.core.agents.core.EdgeRoutingPolicy;
import com.agenticai.core.agents.core.ReasoningDepth;
import com.agenticai.core.agents.core.TuningMode;
import com.agenticai.core.providers.ProviderName;
import com.agenticai.core.providers.modality.TextModelProvider;
import com.agenticai.core.providers.modality.TtsModelProvider;
import com.agenticai.core.providers.modality.VideoModelProvider;
import com.agenticai.core.providers.modality.VoiceModelProvider;
import com.agenticai.core.security.ExperienceMode;
import com.fasterxml.jackson.annotation.JsonIgnoreProperties;
import java.util.List;
import java.util.UUID;

/**
 * The complete, serializable configuration bundle of one {@link Agent} at one
 * moment - the document stored verbatim in {@code agent_version.config_json},
 * and the only thing {@link AgentVersionService#restore} ever reads.
 *
 * <h2>What is in here, and what deliberately is not</h2>
 *
 * <p>Every component below is CONFIG: something a tenant chose, that nothing on
 * the platform regenerates behind their back. The following {@link Agent} fields
 * are excluded on purpose and can never be written by a restore:
 *
 * <ul>
 *   <li>{@code id}, {@code createdBy} - identity and ownership. {@code Agent#getCreatedBy}'s
 *       own javadoc is explicit that it is set exactly once at creation and
 *       "never re-set on update - ownership doesn't change hands by editing an
 *       agent's config." A restore is an edit.
 *   <li>{@code createdAt} - {@code updatable = false} at the JPA level, and also the
 *       clock the FREE-tier 24h edit-lock reads ({@code EditLockPolicy}). Writing
 *       it back from a snapshot would either re-open or slam shut a paywall
 *       window depending on which direction the restore went.
 *   <li>{@code updatedAt} - a restore happened NOW; every {@code Agent} setter stamps
 *       {@code Instant.now()} for us, which is the correct value.
 *   <li>{@code fallbackTriggeredCount}, {@code fallbackFailedCount}, {@code lastFallbackAt} -
 *       runtime statistics, and the sharpest exclusion of the three groups.
 *       {@code AgentRepository#incrementFallbackTriggered}/{@code #incrementFallbackFailed}
 *       are atomic bulk UPDATEs written precisely so two concurrent chat turns
 *       cannot lose an increment to a stale in-memory read. Snapshotting and
 *       restoring them would reintroduce exactly that read-modify-write race.
 *       They are structurally unreachable anyway - {@code Agent} exposes no setter
 *       for any of the three - and this paragraph exists so nobody adds one.
 *   <li>{@code inputSchemaJson}, {@code outputSchemaJson}, {@code schemaVersion} - PLATFORM-
 *       GENERATED by {@code AgentSchemaService#refresh}, not tenant-authored. They
 *       are DERIVED from components that ARE in this bundle
 *       ({@code knowledgeBaseEnabled} and {@code allowedKnowledgeCollectionIds}), so a
 *       restore regenerates them rather than replaying them - see
 *       {@link AgentVersionService#restore} for why that regeneration is
 *       unconditional and mandatory. {@code schemaVersion} in particular is a
 *       monotonic counter whose "0 means never generated" contract a backwards
 *       write would break.
 * </ul>
 *
 * <h2>Why the collections are lists in a JSON document, not child tables</h2>
 *
 * <p>Six of {@link Agent}'s fields are {@code @ElementCollection} sets with their own
 * child tables. Mirroring that structure here would make restore a seven-table
 * read; more importantly it would hide the single most dangerous distinction in
 * this bundle behind a join. Two of the six invert the usual convention:
 *
 * <ul>
 *   <li>{@code allowedToolNames}, {@code allowedKnowledgeCollectionIds},
 *       {@code collaboratorAgentIds}, {@code enabledGuardrails} - EMPTY means
 *       "unrestricted" / "none offered".
 *   <li>{@code allowedCodeIntelRepoIds}, {@code allowedKnowledgeWriteCollectionIds} -
 *       EMPTY means DENY-ALL. These two gate WRITE and EXECUTE reach (code
 *       workspaces that apply patches and run commands; knowledge writes that
 *       every future search turn will retrieve), which is why {@code Agent}'s own
 *       javadoc flips their default.
 * </ul>
 *
 * <p>Because of that inversion, ABSENT and EMPTY must never collapse into each
 * other. In this record they are distinct by construction: {@code null} means the
 * component was not present in the stored document at all (a row written by an
 * older build, before it joined the bundle), while {@code List.of()} means the
 * tenant genuinely had an empty set. {@link AgentConfigSnapshotCodec#apply}
 * treats {@code null} as "leave the live value alone, and TELL the caller which
 * fields were skipped" rather than silently writing an empty set - because
 * writing an empty set would widen nothing for four of these and would silently
 * revoke every granted repo/collection for the other two, while a UI claimed a
 * full rollback had happened.
 *
 * <p>Every capture writes all components, empty lists included, so {@code null} on
 * read genuinely means "older document" and nothing else. The lists are SORTED at
 * capture time (the underlying values are unordered sets) so two snapshots of the
 * same configuration serialize to byte-identical JSON, which is what lets
 * {@link AgentVersionSnapshotService} skip writing a duplicate row.
 *
 * <h2>Boxed primitives</h2>
 *
 * <p>{@code maxTokens}/{@code temperature}/{@code topP} and the eleven boolean flags are
 * primitives on {@link Agent} but boxed here for the same absent-vs-value reason:
 * an older document that predates a flag must deserialize it as {@code null}
 * ("unknown, don't touch") rather than as {@code false} ("the tenant had it off"),
 * which is a materially different and occasionally security-relevant claim.
 *
 * <p>Nullable SCALARS ({@code fallbackModel}, {@code economyModel}, the four modality
 * model strings, {@code resultSchemaJson}) cannot make that distinction - {@code null}
 * is a legitimate stored value for them, so absent and cleared look identical.
 * That is the one honest gap in this scheme, and it is why {@code formatVersion}
 * exists: a future bundle change that needs to disambiguate can branch on it
 * rather than guess.
 *
 * @param formatVersion stamped on every write, read back but not yet branched on.
 *     Present from day one precisely because adding it later is impossible: a
 *     document with no version cannot be told apart from version 1.
 * @param name captured and displayed, but NOT restorable - {@link Agent} has no
 *     {@code setName} (name is write-once via its constructor) and this pass does
 *     not own {@code Agent.java}. {@link AgentConfigSnapshotCodec#apply} reports it
 *     as a skipped field so the surface can say "the name was not rolled back"
 *     rather than quietly implying it was.
 * @param experienceMode nullable is MEANINGFUL - null means "inherit the tenant's
 *     current default", not "unset".
 * @param edgeRoutingPolicy nullable is MEANINGFUL - null means "no server policy,
 *     device preferences decide".
 * @param biometricConsentEnabled captured for audit, restored ONE WAY ONLY (true
 *     to false) - see {@link AgentConfigSnapshotCodec#apply}. This flag gates
 *     biometric/special-category processing under GDPR Art.9 and India's DPDP
 *     Act, and consent is not something a rollback button may re-grant on a
 *     tenant's behalf.
 * @param resultSchemaJson TENANT-AUTHORED job result schema. Snapshotted and
 *     restored, unlike its easily-confused neighbour {@code outputSchemaJson},
 *     which is platform-generated and excluded - {@code Agent}'s own javadoc spells
 *     out why conflating the two silently destroys tenant work. Known gap,
 *     documented rather than hidden: this field is written OUTSIDE
 *     {@code AgentService} (by the agent-job result-schema endpoints, which save
 *     straight through {@code AgentRepository}), so a change to it produces no
 *     version row, and restoring an older version will therefore revert it.
 * @param allowedToolNames empty = unrestricted; null = absent from an older document.
 * @param allowedKnowledgeCollectionIds empty = every collection searchable; null = absent.
 * @param allowedCodeIntelRepoIds empty = DENY-ALL (write/execute reach); null = absent.
 * @param allowedKnowledgeWriteCollectionIds empty = DENY-ALL (write reach); null = absent.
 * @param collaboratorAgentIds empty = no delegation tool offered; null = absent.
 * @param enabledGuardrails empty = no guardrails; null = absent. Same known gap as
 *     {@code resultSchemaJson}: {@code AgentGuardrailService#updateAgentGuardrails}
 *     writes this field straight through {@code AgentRepository}, so guardrail
 *     changes are not themselves versioned.
 */
@JsonIgnoreProperties(ignoreUnknown = true)
public record AgentConfigSnapshot(
    Integer formatVersion,

    String name,
    String systemPrompt,
    ProviderName providerName,
    String model,

    Integer maxTokens,
    Double temperature,
    Double topP,

    // Restored together, never one without the other (Agent#setFallbackProvider).
    ProviderName fallbackProviderName,
    String fallbackModel,

    AgentAutonomyTier autonomyTier,
    TuningMode tuningMode,
    ReasoningDepth reasoningDepth,
    ExperienceMode experienceMode,
    EdgeRoutingPolicy edgeRoutingPolicy,

    Boolean knowledgeBaseEnabled,
    Boolean sarvamEnabled,
    Boolean e2bEnabled,
    Boolean codeWorkspaceEnabled,
    Boolean knowledgeWriteEnabled,
    Boolean shareMemoryWithTenant,
    Boolean biometricConsentEnabled,
    Boolean responseCachingEnabled,
    Boolean semanticResponseCachingEnabled,

    // All four restored together (Agent#setCostRouting).
    Boolean costRoutingEnabled,
    ProviderName economyProviderName,
    String economyModel,
    Double costRoutingJevThreshold,

    VoiceModelProvider voiceModelProvider,
    String voiceModel,
    VideoModelProvider videoModelProvider,
    String videoModel,
    TextModelProvider textModelProvider,
    String textModel,
    TtsModelProvider ttsProvider,
    String ttsModel,

    String resultSchemaJson,

    List<String> allowedToolNames,
    List<UUID> allowedKnowledgeCollectionIds,
    List<String> allowedCodeIntelRepoIds,
    List<UUID> allowedKnowledgeWriteCollectionIds,
    List<UUID> collaboratorAgentIds,
    List<String> enabledGuardrails,

    // xAI Agent Tools API opt-in (migration V239, added 2026-09-23 - null in
    // every document written before this component existed, restored via the
    // same applyFlag "absent means leave alone" path as the flags above).
    Boolean xaiServerToolsEnabled,

    // Extra sampling controls (migration V331). stopSequences is always written
    // by capture (empty list included), so null there means "predates the field"
    // and the whole group is left alone on restore; the other four are
    // legitimately null when unset.
    Integer topK,
    List<String> stopSequences,
    Double frequencyPenalty,
    Double presencePenalty,
    Integer seed
) {

    /**
     * The shape of documents this build writes. Bump only when the MEANING of an
     * existing component changes, or when a nullable scalar's absent/cleared
     * ambiguity has to be resolved - simply ADDING a component does not need a
     * bump, because a new one is unambiguously {@code null} in every older
     * document by definition.
     */
    public static final int CURRENT_FORMAT_VERSION = 1;
}
