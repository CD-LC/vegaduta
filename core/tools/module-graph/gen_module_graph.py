#!/usr/bin/env python3
"""Generate docs/architecture/core-module-graph.md from core/*/pom.xml.

ADR-0011 phase 0. Parses the reactor module list in core/pom.xml, then every
module's <dependencies>, and keeps only edges to sibling reactor modules. The
output (Markdown table + Mermaid graph + kernel/vendor classification) is
deterministic - no timestamps - so it can be diffed in CI.

Usage (from the repo root or anywhere):
    python core/tools/module-graph/gen_module_graph.py            # (re)write the doc
    python core/tools/module-graph/gen_module_graph.py --check    # exit 1 if the doc is stale
    python core/tools/module-graph/gen_module_graph.py --stdout   # print, don't write

Stdlib only (xml.etree), Python 3.8+.
"""
from __future__ import annotations

import argparse
import pathlib
import sys
import xml.etree.ElementTree as ET

CORE = pathlib.Path(__file__).resolve().parents[2]
REPO = CORE.parent
OUT = REPO / "docs" / "architecture" / "core-module-graph.md"
NS = {"m": "http://maven.apache.org/POM/4.0.0"}
GROUP = "com.agenticai"

# --- Classification (ADR-0011 section 2.1 / 9.1). Keep in sync with
# --- core/app/src/test/java/com/agenticai/core/archrules/ModuleBoundaryRulesTest.java
VENDOR = {
    "elevenlabs": "ElevenLabs TTS/voice clone/music",
    "sarvam": "Sarvam AI (LLM, STT/TTS, translate)",
    "google": "Google Workspace OAuth + tools",
    "imagegen": "Image/video generation backends",
    "payments": "UPI mandate payments",
}
KERNEL_WITH_VENDOR_CODE = {
    "billing": "Razorpay + PhonePe gateways in billing.gateway",
    "chat": "16 LLM *ChatClientFactory classes (closed ProviderName)",
    "knowledge": "embeddings / OCR / sidecar clients",
    "omnichannel": "11 channel types + Twilio sub-packages (closed ChannelType)",
    "providers": "kernel provider registry; LLM validators + OpenAI/sidecar modality adapters",
}
DISTRIBUTION = {"app", "app-worker", "app-jobs"}


def text(el, path):
    found = el.find(path, NS)
    return found.text.strip() if found is not None and found.text else None


def reactor_modules():
    root = ET.parse(CORE / "pom.xml").getroot()
    return [m.text.strip() for m in root.findall("m:modules/m:module", NS)]


def module_info(name, modules):
    pom = ET.parse(CORE / name / "pom.xml").getroot()
    artifact = text(pom, "m:artifactId")
    deps = []
    for dep in pom.findall("m:dependencies/m:dependency", NS):
        if text(dep, "m:groupId") != GROUP:
            continue
        aid = text(dep, "m:artifactId")
        if aid not in modules:
            continue
        scope = text(dep, "m:scope") or "compile"
        deps.append((aid, scope))
    src = CORE / name / "src" / "main" / "java"
    files = sum(1 for _ in src.rglob("*.java")) if src.is_dir() else 0
    return artifact, sorted(deps), files


def kind(name):
    if name in VENDOR:
        return "vendor"
    if name in DISTRIBUTION:
        return "distribution"
    if name in KERNEL_WITH_VENDOR_CODE:
        return "kernel (hosts vendor code)"
    return "kernel"


def render():
    modules = reactor_modules()
    # artifactId == directory name for every reactor module; assert it.
    info = {}
    for name in modules:
        artifact, deps, files = module_info(name, set(modules))
        if artifact != name:
            raise SystemExit(f"module dir {name} has artifactId {artifact}; script assumes they match")
        info[name] = (deps, files)

    compile_edges = [(a, b) for a, (deps, _) in info.items() for b, s in deps if s in ("compile", "runtime")]
    kernel_to_vendor = sorted((a, b) for a, b in compile_edges
                              if b in VENDOR and a not in VENDOR and a not in DISTRIBUTION)
    vendor_to_vendor = sorted((a, b) for a, b in compile_edges if a in VENDOR and b in VENDOR)

    out = []
    w = out.append
    w("# Core module graph")
    w("")
    w("<!-- GENERATED by core/tools/module-graph/gen_module_graph.py from core/*/pom.xml. Do not hand-edit;")
    w("     re-run the script (it also has --check for CI). -->")
    w("")
    w("ADR-0011 phase 0 baseline. Edges are `<dependency>` entries between sibling reactor modules")
    w("(`groupId` `com.agenticai`). Test-scope edges are marked `(test)`. Classification follows")
    w("ADR-0011 section 2.1 and is mirrored by the ArchUnit rules in")
    w("`core/app/src/test/java/com/agenticai/core/archrules/ModuleBoundaryRulesTest.java`.")
    w("")
    w(f"- Reactor modules: **{len(modules)}**")
    w(f"- Sibling edges (compile/runtime): **{len(compile_edges)}**")
    w(f"- Kernel -> vendor module edges: **{len(kernel_to_vendor)}**"
      + (" (" + ", ".join(f"{a} -> {b}" for a, b in kernel_to_vendor) + ")" if kernel_to_vendor else ""))
    w(f"- Vendor -> vendor module edges: **{len(vendor_to_vendor)}**"
      + (" (" + ", ".join(f"{a} -> {b}" for a, b in vendor_to_vendor) + ")" if vendor_to_vendor else ""))
    w("")
    w("## Classification")
    w("")
    w("| Kind | Meaning |")
    w("|---|---|")
    w("| vendor | Adapter module for one external vendor. Target: a provider starter (ADR-0011 phase 4). |")
    w("| kernel (hosts vendor code) | Kernel module that still contains vendor adapters in sub-packages. |")
    w("| kernel | Vendor-neutral platform code. Must not import vendor modules. |")
    w("| distribution | Composition root / deployable (`@SpringBootApplication`). May depend on anything. |")
    w("")
    w("## Modules")
    w("")
    w("| Module | Kind | Main src files | Depends on (sibling modules) | Notes |")
    w("|---|---|---:|---|---|")
    for name in sorted(modules):
        deps, files = info[name]
        dep_s = ", ".join(
            (f"**{d}**" if d in VENDOR else d) + ("" if s in ("compile", "runtime") else f" ({s})")
            for d, s in deps) or "(none)"
        note = VENDOR.get(name) or KERNEL_WITH_VENDOR_CODE.get(name) or ""
        w(f"| {name} | {kind(name)} | {files} | {dep_s} | {note} |")
    w("")
    w("## Graph")
    w("")
    w("Vendor modules are highlighted; distributions are dashed. Test-scope edges are omitted.")
    w("")
    w("```mermaid")
    w("graph LR")
    ids = {name: name.replace("-", "_") for name in modules}
    for name in sorted(modules):
        w(f"  {ids[name]}[{name}]")
    for a, b in sorted(compile_edges):
        w(f"  {ids[a]} --> {ids[b]}")
    w("  classDef vendor fill:#fde2e1,stroke:#c0392b,color:#000")
    w("  classDef mixed fill:#fff4d6,stroke:#b7950b,color:#000")
    w("  classDef dist fill:#eef,stroke:#446,stroke-dasharray: 4 3,color:#000")
    for name in sorted(modules):
        if name in VENDOR:
            w(f"  class {ids[name]} vendor")
        elif name in KERNEL_WITH_VENDOR_CODE:
            w(f"  class {ids[name]} mixed")
        elif name in DISTRIBUTION:
            w(f"  class {ids[name]} dist")
    w("```")
    w("")
    w("## Who depends on each vendor module")
    w("")
    w("| Vendor module | Depended on by |")
    w("|---|---|")
    for v in sorted(VENDOR):
        users = sorted(a for a, b in compile_edges if b == v)
        w(f"| {v} | {', '.join(users) or '(none)'} |")
    w("")
    return "\n".join(out)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--check", action="store_true", help="fail if the committed doc differs")
    ap.add_argument("--stdout", action="store_true")
    args = ap.parse_args()
    doc = render()
    if args.stdout:
        sys.stdout.write(doc)
        return 0
    if args.check:
        current = OUT.read_text(encoding="utf-8").replace("\r\n", "\n") if OUT.exists() else ""
        if current != doc:
            sys.stderr.write(f"{OUT} is stale - re-run {pathlib.Path(__file__).name}\n")
            return 1
        print("module graph up to date")
        return 0
    with open(OUT, "w", encoding="utf-8", newline="\n") as fh:  # write_text(newline=) needs 3.10
        fh.write(doc)
    print(f"wrote {OUT.relative_to(REPO)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
